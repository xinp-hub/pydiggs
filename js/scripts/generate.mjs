// Generates everything under src/generated/ and schemas/ from pydiggs's own contracts:
//
//   ../src/pydiggs/findings/diggs-findings-1.1.schema.json  -> src/generated/findings.ts
//   ../src/pydiggs/model/diggs-model-1.0.schema.json        -> src/generated/model.ts
//   ../src/pydiggs/server/openapi.json                      -> src/generated/http.ts
//   ../examples/browser-worker/worker.mjs (the pins)        -> src/generated/pins.ts
//   both JSON Schemas, byte for byte                        -> schemas/
//   ../src/pydiggs/findings/diggs-findings-1.0.schema.json  -> schemas/ (the earlier
//     version: unchanged, still shipped, and what diggs-model 1.0's notes refer to)
//
//   node scripts/generate.mjs           write the files
//   node scripts/generate.mjs --check   exit 1 if a file on disk differs (CI)
//
// No dependencies. It handles the JSON Schema keywords these contracts use and stops on
// any other, so a new keyword is a decision here and never a silently wrong type.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const JS_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = join(JS_ROOT, "..");

const FINDINGS_SCHEMA = "src/pydiggs/findings/diggs-findings-1.1.schema.json";
// Earlier diggs-findings versions. Each stays shipped byte for byte, and a $ref to one
// resolves to the current types: a minor version only adds to the one before it.
const EARLIER_FINDINGS_SCHEMAS = ["src/pydiggs/findings/diggs-findings-1.0.schema.json"];
const MODEL_SCHEMA = "src/pydiggs/model/diggs-model-1.0.schema.json";
const OPENAPI = "src/pydiggs/server/openapi.json";
const WORKER = "examples/browser-worker/worker.mjs";

const HEADER = (source) =>
  `// Generated by scripts/generate.mjs from ${source}. Do not edit: change the source and run \`npm run generate\`.\n`;

// --- JSON Schema -> TypeScript -------------------------------------------------------

// Keywords that only constrain values a TypeScript type cannot express.
const VALIDATION_ONLY = new Set([
  "pattern",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "minItems",
  "maxItems",
  "format",
  "contentMediaType",
]);
const ANNOTATIONS = new Set(["title", "description", "examples", "$schema", "$id", "$defs"]);
const STRUCTURAL = new Set([
  "type",
  "properties",
  "required",
  "additionalProperties",
  "items",
  "enum",
  "const",
  "$ref",
  "anyOf",
  "allOf",
]);

function checkKeywords(schema, where) {
  for (const key of Object.keys(schema)) {
    if (!STRUCTURAL.has(key) && !VALIDATION_ONLY.has(key) && !ANNOTATIONS.has(key)) {
      throw new Error(`${where}: unsupported JSON Schema keyword "${key}"`);
    }
  }
}

const pascal = (name) =>
  name
    .split(/[_-]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const propertyKey = (name) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

function jsdoc(schema, indent) {
  const lines = [];
  if (typeof schema.description === "string") lines.push(schema.description);
  if (Array.isArray(schema.examples) && schema.examples.length > 0) {
    lines.push(`Examples: ${schema.examples.map((example) => JSON.stringify(example)).join(", ")}.`);
  }
  if (lines.length === 0) return "";
  const text = lines.join(" ").replaceAll("*/", "*\\/");
  return `${indent}/** ${text} */\n`;
}

// An `allOf` entry that is an if/then/else refinement narrows values the base type
// already allows, so it adds nothing to the TypeScript type.
const isRefinement = (entry) => "if" in entry;

class Emitter {
  /** @param {(ref: string) => string} resolveRef */
  constructor(resolveRef) {
    this.resolveRef = resolveRef;
  }

  /** The type expression for `schema`, written at `indent`. */
  type(schema, where, indent = "") {
    if (schema === true) return "unknown";
    checkKeywords(schema, where);
    if ("$ref" in schema) return this.resolveRef(schema.$ref);
    if ("const" in schema) return JSON.stringify(schema.const);
    if ("enum" in schema) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
    if ("anyOf" in schema) {
      return schema.anyOf.map((part, i) => this.type(part, `${where}/anyOf/${i}`, indent)).join(" | ");
    }
    if ("allOf" in schema && !schema.allOf.every(isRefinement)) {
      throw new Error(`${where}: allOf is supported only as the base of a named definition`);
    }
    const types = Array.isArray(schema.type) ? schema.type : [schema.type];
    if (types[0] === undefined) {
      return "properties" in schema ? this.object(schema, where, indent) : "unknown";
    }
    return types.map((type) => this.single(type, schema, where, indent)).join(" | ");
  }

  single(type, schema, where, indent) {
    switch (type) {
      case "null":
        return "null";
      case "string":
        return "string";
      case "boolean":
        return "boolean";
      case "integer":
      case "number":
        return "number";
      case "array": {
        if (!("items" in schema)) return "unknown[]";
        const item = this.type(schema.items, `${where}/items`, indent);
        return /[ |]/.test(item) && !item.startsWith("{") ? `(${item})[]` : `${item}[]`;
      }
      case "object":
        return this.object(schema, where, indent);
      default:
        throw new Error(`${where}: unsupported type "${type}"`);
    }
  }

  object(schema, where, indent) {
    const body = this.members(schema, where, `${indent}  `);
    return body === "" ? "{ [key: string]: unknown }" : `{\n${body}${indent}}`;
  }

  /** The members of an object type, one per line, each at `indent`. */
  members(schema, where, indent) {
    const required = new Set(schema.required ?? []);
    const properties = Object.entries(schema.properties ?? {});
    for (const name of required) {
      if (!(name in (schema.properties ?? {}))) {
        throw new Error(`${where}: required property "${name}" is not declared`);
      }
    }
    let out = "";
    let anyOptional = false;
    for (const [name, property] of properties) {
      const optional = !required.has(name);
      anyOptional ||= optional;
      out += jsdoc(property, indent);
      out += `${indent}${propertyKey(name)}${optional ? "?" : ""}: ${this.type(property, `${where}/${name}`, indent)};\n`;
    }
    const extra = schema.additionalProperties;
    if (extra !== undefined && extra !== false) {
      const value = this.type(extra, `${where}/additionalProperties`, indent);
      out += `${indent}[key: string]: ${value}${anyOptional ? " | undefined" : ""};\n`;
    }
    return out;
  }

  /** A named, exported declaration for `schema`. */
  declaration(name, schema, where) {
    checkKeywords(schema, where);
    const bases = (schema.allOf ?? []).filter((entry) => !isRefinement(entry));
    const isObject = schema.type === "object" && ("properties" in schema || bases.length > 0);
    if (!isObject) {
      if (bases.length > 0) throw new Error(`${where}: allOf on a non-object definition`);
      return `${jsdoc(schema, "")}export type ${name} = ${this.type({ ...schema, description: undefined, examples: undefined }, where)};\n`;
    }
    const extended = bases.map((base, i) => {
      if (Object.keys(base).length !== 1 || !("$ref" in base)) {
        throw new Error(`${where}/allOf/${i}: only a bare $ref can be a base`);
      }
      return this.resolveRef(base.$ref);
    });
    const heritage = extended.length > 0 ? ` extends ${extended.join(", ")}` : "";
    return `${jsdoc(schema, "")}export interface ${name}${heritage} {\n${this.members(schema, where, "  ")}}\n`;
  }
}

// `description: undefined` above is how a declaration keeps its doc comment on the
// alias and not inside the type; checkKeywords must ignore those placeholders.
const stripUndefined = (schema) => JSON.parse(JSON.stringify(schema));

function emitSchema({ schema, prefix, rootName, sourcePath, external }) {
  const names = new Map(Object.keys(schema.$defs ?? {}).map((key) => [key, prefix + pascal(key)]));
  const imports = new Map();
  const emitter = new Emitter((ref) => {
    const [url, pointer] = ref.split("#");
    const match = /^\/\$defs\/([^/]+)$/.exec(pointer ?? "");
    if (!match) throw new Error(`${sourcePath}: unsupported $ref "${ref}"`);
    if (url === "" || url === schema.$id) {
      const name = names.get(match[1]);
      if (!name) throw new Error(`${sourcePath}: $ref to unknown definition "${ref}"`);
      return name;
    }
    const other = external?.[url];
    if (!other) throw new Error(`${sourcePath}: $ref to unknown schema "${ref}"`);
    const name = other.prefix + pascal(match[1]);
    imports.set(name, other.module);
    return name;
  });

  const blocks = [];
  const realType = emitter.type.bind(emitter);
  emitter.type = (node, where, indent) => realType(node === true ? node : stripUndefined(node), where, indent);
  blocks.push(emitter.declaration(rootName, stripUndefined({ ...schema, $defs: undefined }), sourcePath));
  for (const [key, definition] of Object.entries(schema.$defs ?? {})) {
    blocks.push(emitter.declaration(names.get(key), definition, `${sourcePath}#/$defs/${key}`));
  }
  const importLines = [...imports]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, module]) => `import type { ${name} } from "${module}";\n`)
    .join("");
  const exported = [rootName, ...names.values()];
  return {
    text: `${HEADER(sourcePath)}\n${importLines}${importLines ? "\n" : ""}${blocks.join("\n")}`,
    exported,
  };
}

// --- Inputs ---------------------------------------------------------------------------

const readText = (relative) => readFileSync(join(REPO_ROOT, relative), "utf8");
const findingsText = readText(FINDINGS_SCHEMA);
const modelText = readText(MODEL_SCHEMA);
const findingsSchema = JSON.parse(findingsText);
const earlierFindings = EARLIER_FINDINGS_SCHEMAS.map((path) => {
  const text = readText(path);
  return { path, text, id: JSON.parse(text).$id };
});
const findingsTypes = { prefix: "DiggsFindings", module: "./findings.ts" };
const modelSchema = JSON.parse(modelText);
const openapi = JSON.parse(readText(OPENAPI));
const workerText = readText(WORKER);

// --- findings.ts and model.ts ---------------------------------------------------------

const findings = emitSchema({
  schema: findingsSchema,
  prefix: "DiggsFindings",
  rootName: "DiggsFindingsDocument",
  sourcePath: FINDINGS_SCHEMA,
});
const model = emitSchema({
  schema: modelSchema,
  prefix: "DiggsModel",
  rootName: "DiggsModelDocument",
  sourcePath: MODEL_SCHEMA,
  external: Object.fromEntries(
    [findingsSchema.$id, ...earlierFindings.map((earlier) => earlier.id)].map((id) => [id, findingsTypes]),
  ),
});

// The OpenAPI document derives its DiggsFindings* and DiggsModel* components from the
// same two schemas. Holding the names equal keeps this package, the OpenAPI document
// and any client generated from it speaking of the same types.
const components = openapi.components.schemas;
const expected = Object.keys(components).filter((name) => /^Diggs(Findings|Model)/.test(name));
const generated = new Set([...findings.exported, ...model.exported]);
const missing = expected.filter((name) => !generated.has(name));
const unknown = [...generated].filter((name) => !expected.includes(name));
if (missing.length > 0 || unknown.length > 0) {
  throw new Error(
    `type names differ from ${OPENAPI} components: missing ${JSON.stringify(missing)}, extra ${JSON.stringify(unknown)}`,
  );
}

// --- http.ts ---------------------------------------------------------------------------

const HTTP_COMPONENTS = ["Problem", "Ready", "RuleInfo", "Versions", "SarifLog"];

function queryParameter(path, method, name) {
  const parameter = (openapi.paths[path]?.[method]?.parameters ?? []).find((p) => p.name === name);
  if (!parameter) throw new Error(`${OPENAPI}: no "${name}" parameter on ${method} ${path}`);
  return parameter;
}

function emitHttp() {
  const emitter = new Emitter((ref) => {
    throw new Error(`${OPENAPI}: unexpected $ref "${ref}" in a component this package generates`);
  });
  const blocks = HTTP_COMPONENTS.map((name) => {
    const component = components[name];
    if (!component) throw new Error(`${OPENAPI}: no component "${name}"`);
    return emitter.declaration(name, stripUndefined({ ...component, title: undefined }), `${OPENAPI}#${name}`);
  });

  const version = queryParameter("/v1/validate", "post", "diggs_version");
  const readVersion = queryParameter("/v1/read", "post", "diggs_version");
  if (JSON.stringify(version.schema) !== JSON.stringify(readVersion.schema)) {
    throw new Error(`${OPENAPI}: diggs_version differs between /v1/validate and /v1/read`);
  }
  blocks.push(
    `/** ${version.description} */\nexport type DiggsVersion = ${emitter.type(version.schema, "diggs_version")};\n`,
  );

  // `checks` is a comma-separated list; its pattern is ^(a|b|c)(,(a|b|c))*$.
  const checks = queryParameter("/v1/validate", "post", "checks");
  const shape = /^\^\(([a-zA-Z|]+)\)\(,\(([a-zA-Z|]+)\)\)\*\$$/.exec(checks.schema.pattern ?? "");
  if (!shape || shape[1] !== shape[2]) {
    throw new Error(`${OPENAPI}: the "checks" pattern is no longer ^(a|b)(,(a|b))*$`);
  }
  const steps = shape[1].split("|");
  blocks.push(
    `/** A step \`validate\` can be asked to run. */\nexport type ValidateCheck = ${steps.map((s) => JSON.stringify(s)).join(" | ")};\n`,
  );

  const step = queryParameter("/v1/rules", "get", "step");
  blocks.push(`/** ${step.description} */\nexport type RuleStep = ${emitter.type(step.schema, "step")};\n`);

  return `${HEADER(OPENAPI)}\n${blocks.join("\n")}`;
}

// --- pins.ts ---------------------------------------------------------------------------

function workerConstant(name, pattern) {
  const match = new RegExp(`^const ${name} = ${pattern};`, "m").exec(workerText);
  if (!match) throw new Error(`${WORKER}: cannot find const ${name}`);
  return match[1];
}

// js/pydiggs-wheel.json pins the published wheel of PYDIGGS_VERSION by its sha256, so
// the worker can check what it downloads. It is written after a pyDIGGS release, by
// scripts/follow-pydiggs.mjs from PyPI's own record. Until it names PYDIGGS_VERSION
// (between a pyDIGGS release PR and that update), the worker falls back to micropip,
// which checks the wheel against PyPI's index instead.
function pinnedWheel(pydiggs) {
  const path = join(JS_ROOT, "pydiggs-wheel.json");
  if (!existsSync(path)) return null;
  const pin = JSON.parse(readFileSync(path, "utf8"));
  if (pin.version !== pydiggs) return null;
  const url = new URL(pin.url);
  if (url.protocol !== "https:" || url.hostname !== "files.pythonhosted.org" || !url.pathname.endsWith(`/${pin.filename}`)) {
    throw new Error("pydiggs-wheel.json: url must be the https://files.pythonhosted.org/ URL of its filename");
  }
  if (pin.filename !== `pydiggs-${pydiggs}-py3-none-any.whl` || !/^[0-9a-f]{64}$/.test(pin.sha256)) {
    throw new Error("pydiggs-wheel.json: filename or sha256 is malformed");
  }
  return { url: pin.url, sha256: pin.sha256 };
}

function emitPins() {
  const pyodide = workerConstant("PYODIDE_VERSION", '"([0-9.]+)"');
  const sri = workerConstant("PYODIDE_SRI", '"(sha384-[A-Za-z0-9+/=]+)"');
  const pydiggs = workerConstant("PYDIGGS_VERSION", '"([0-9A-Za-z.+-]+)"');
  const maxBytes = workerConstant("MAX_BYTES", "(25 \\* 1024 \\* 1024)");
  const wheel = pinnedWheel(pydiggs);
  return [
    HEADER(WORKER),
    "/** The Pyodide release this package is tested with. */",
    `export const PYODIDE_VERSION: string = ${JSON.stringify(pyodide)};`,
    "/** Subresource Integrity hash of that release's pyodide.mjs loader. */",
    `export const PYODIDE_SRI: string = ${JSON.stringify(sri)};`,
    "/** The pydiggs release the worker installs from PyPI unless given a wheel URL. */",
    `export const PYDIGGS_VERSION: string = ${JSON.stringify(pydiggs)};`,
    "/**",
    " * The published wheel of PYDIGGS_VERSION and its sha256, from PyPI; null until",
    " * js/pydiggs-wheel.json names that version (then micropip installs it by version).",
    " */",
    `export const PYDIGGS_WHEEL: { url: string; sha256: string } | null = ${wheel ? `{ url: ${JSON.stringify(wheel.url)}, sha256: ${JSON.stringify(wheel.sha256)} }` : "null"};`,
    "/** Largest document the worker accepts, in bytes, unless configured lower. */",
    `export const DEFAULT_MAX_BYTES: number = ${maxBytes};`,
    "/** The diggs-findings schema these types were generated from. */",
    `export const FINDINGS_SCHEMA_URL: string = ${JSON.stringify(findingsSchema.$id)};`,
    "/** The diggs-model schema these types were generated from. */",
    `export const MODEL_SCHEMA_URL: string = ${JSON.stringify(modelSchema.$id)};`,
    "",
  ].join("\n");
}

// --- Write or check ------------------------------------------------------------------

const outputs = new Map([
  ["src/generated/findings.ts", findings.text],
  ["src/generated/model.ts", model.text],
  ["src/generated/http.ts", emitHttp()],
  ["src/generated/pins.ts", emitPins()],
  [`schemas/${FINDINGS_SCHEMA.split("/").at(-1)}`, findingsText],
  ...earlierFindings.map((earlier) => [`schemas/${earlier.path.split("/").at(-1)}`, earlier.text]),
  ["schemas/diggs-model-1.0.schema.json", modelText],
]);

const check = process.argv.includes("--check");
const stale = [];
for (const [relative, text] of outputs) {
  const path = join(JS_ROOT, relative);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) continue;
  stale.push(relative);
  if (!check) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}

if (check && stale.length > 0) {
  console.error(`Out of date: ${stale.join(", ")}\nRun \`npm run generate\` in js/ and commit the result.`);
  process.exit(1);
}
console.log(check ? "Generated files are up to date." : `Wrote ${stale.length} file(s).`);
