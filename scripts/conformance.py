# External files are downloaded from these hosts only, over HTTPS, at a pinned commit.
ALLOWED_HOSTS = frozenset({"raw.githubusercontent.com", "gitlab.com"})
MAX_BYTES = 64 * 2**20
TIMEOUT_S = 60.0

_HEX40 = re.compile(r"[0-9a-f]{40}")
_HEX64 = re.compile(r"[0-9a-f]{64}")
_GITHUB_REPO = re.compile(r"https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)")
# A GitLab project may sit in nested groups: https://gitlab.com/<group>/<subgroup>/<name>.
_GITLAB_REPO = re.compile(r"https://gitlab\.com/((?:[A-Za-z0-9_.-]+/){1,8}[A-Za-z0-9_.-]+)")
# Every component of a corpus path must match this (no "..", no separators, no streams).
_SAFE_COMPONENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9._ +-]*")
# A DIGGS profile name, as pydiggs spells them (2.5.a, 2.6, 3.0.0, 3.1-dev).
_PROFILE = re.compile(r"[0-9][0-9A-Za-z.-]{0,31}")
_HEADER = (
    "# Expected pyDIGGS outcome for every conformance corpus file.\n"
    "# Generated by scripts/conformance.py record. Review changes like a golden file.\n"
)
_MODEL_HEADER = (
    "# What a reader must produce for every conformance corpus file (diggs-model census).\n"
    "# Generated by scripts/conformance.py record --model. Review changes like a golden file.\n"
)
_XLINK_HREF = "{http://www.w3.org/1999/xlink}href"
_GML_ID = "{http://www.opengis.net/gml/3.2}id"


class CorpusError(Exception):
    """A corpus file is missing, too large, or does not match its digest (exit 1)."""


class ManifestError(CorpusError):
    """A manifest is malformed or names a disallowed source (exit 2)."""


class _Response(Protocol):
    def read(self, amt: int = ..., /) -> bytes: ...  # pragma: no cover - protocol

    def geturl(self) -> str: ...  # pragma: no cover - protocol

    def __enter__(self) -> _Response: ...  # pragma: no cover - protocol

    def __exit__(self, *exc: object) -> None: ...  # pragma: no cover - protocol


Opener = Callable[[str, float], _Response]


@dataclass(frozen=True)
class Entry:
    """One corpus file.

    Attributes:
        key: Stable corpus id, ``official/<rel>`` or ``<source>/<rel>``.
        path: Where the file is (or will be) on disk.
        sha256: Digest after CRLF -> LF normalisation.
        url: Download URL for external files; ``None`` for vendored ones.
        size: Expected size in bytes for external files; ``None`` for vendored ones.
        diggs_version: Profile to validate with; ``None`` lets pyDIGGS detect it.
    """

    key: str
    path: Path
    sha256: str
    url: str | None = None
    size: int | None = None
    diggs_version: str | None = None


def digest(data: bytes) -> str:
    r"""Return the sha256 of ``data`` after CRLF -> LF normalisation.

    Matches ``scripts/sync_reference.py``, so a checkout with ``core.autocrlf`` verifies.

    Examples:
        >>> digest(b"a\r\nb") == digest(b"a\nb")
        True
    """
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def _safe_rel(rel: str, where: str) -> str:
    parts = rel.split("/")
    if not parts or any(not _SAFE_COMPONENT.fullmatch(p) or p in {".", ".."} for p in parts):
        msg = f"{where}: unsafe path {rel!r}"
        raise ManifestError(msg)
    return rel


def _require(table: dict[str, Any], key: str, where: str) -> Any:
    if key not in table:
        msg = f"{where}: missing {key!r}"
        raise ManifestError(msg)
    return table[key]


def _load_toml(path: Path) -> dict[str, Any]:
    """Parse a manifest; an unreadable or malformed file is a :class:`ManifestError`."""
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        msg = f"{path.name}: {exc}"
        raise ManifestError(msg) from exc


def load_vendored(provenance: Path = VENDORED_PROVENANCE) -> list[Entry]:
    """Return the vendored official examples as corpus entries."""
    data = _load_toml(provenance)
    base = provenance.parent
    entries = []
    for rel, meta in sorted(data.get("files", {}).items()):
        where = f"{provenance.name} [{rel}]"
        sha = str(_require(meta, "sha256", where))
        if not _HEX64.fullmatch(sha):
            msg = f"{where}: sha256 is not 64 lowercase hex digits"
            raise ManifestError(msg)
        entries.append(Entry(f"official/{_safe_rel(rel, where)}", base / rel, sha))
    return entries


def _raw_prefix(repo: str, commit: str, where: str) -> str:
    """Return the URL prefix of a repository's raw files at ``commit``.

    Examples:
        >>> _raw_prefix("https://github.com/o/r", "c0ffee", "x")
        'https://raw.githubusercontent.com/o/r/c0ffee/'
        >>> _raw_prefix("https://gitlab.com/g/sub/r", "c0ffee", "x")
        'https://gitlab.com/g/sub/r/-/raw/c0ffee/'
    """
    if (match := _GITHUB_REPO.fullmatch(repo)) is not None:
        return f"https://raw.githubusercontent.com/{match.group(1)}/{match.group(2)}/{commit}/"
    match = _GITLAB_REPO.fullmatch(repo)
    if match is not None and not {".", "..", "-"} & set(match.group(1).split("/")):
        return f"https://gitlab.com/{match.group(1)}/-/raw/{commit}/"
    msg = f"{where}: repo must be https://github.com/<owner>/<name> or https://gitlab.com/<path>"
    raise ManifestError(msg)


def load_external(corpus: Path = CORPUS, cache: Path = CACHE) -> list[Entry]:
    """Return the external files listed in ``corpus`` as corpus entries."""
    data = _load_toml(corpus)
    # Each source maps to the URL prefix of its files at the pinned commit.
    sources: dict[str, str] = {}
    for name, meta in data.get("sources", {}).items():
        where = f"{corpus.name} [sources.{name}]"
        _safe_rel(name, where)
        repo = str(_require(meta, "repo", where))
        commit = str(_require(meta, "commit", where))
        _require(meta, "license", where)
        if not _HEX40.fullmatch(commit):
            msg = f"{where}: commit must be a full 40-character sha"
            raise ManifestError(msg)
        sources[name] = _raw_prefix(repo, commit, where)

    entries = []
    for key, meta in sorted(data.get("files", {}).items()):
        where = f"{corpus.name} [files.{key!r}]"
        source, _, rel = key.partition("/")
        if source not in sources:
            msg = f"{where}: key must start with a declared source name"
            raise ManifestError(msg)
        _safe_rel(rel, where)
        upstream = _safe_rel(str(_require(meta, "path", where)), where)
        sha = str(_require(meta, "sha256", where))
        size = _require(meta, "size", where)
        if not _HEX64.fullmatch(sha):
            msg = f"{where}: sha256 is not 64 lowercase hex digits"
            raise ManifestError(msg)
        if not isinstance(size, int) or not 0 < size <= MAX_BYTES:
            msg = f"{where}: size must be an integer between 1 and {MAX_BYTES}"
            raise ManifestError(msg)
        url = sources[source] + urllib.parse.quote(upstream)
        version = meta.get("diggs_version")
        entries.append(
            Entry(
                key, cache / source / rel, sha, url, size, None if version is None else str(version)
            )
        )
    return entries


def with_profiles(entries: Sequence[Entry], corpus: Path = CORPUS) -> list[Entry]:
    """Return ``entries`` plus one entry per extra profile in ``corpus``'s ``[profiles]``.

    ``[profiles]`` maps a corpus key to a list of DIGGS profiles. Each becomes an entry
    keyed ``<key>@<profile>`` for the same file, validated with that profile.
    """
    table = _load_toml(corpus).get("profiles", {})
    if not isinstance(table, dict):
        msg = f"{corpus.name} [profiles]: must be a table"
        raise ManifestError(msg)
    by_key = {e.key: e for e in entries}
    extra: list[Entry] = []
    for key, profiles in sorted(table.items()):
        where = f"{corpus.name} [profiles] {key!r}"
        if key not in by_key:
            msg = f"{where}: not a corpus file"
            raise ManifestError(msg)
        if not isinstance(profiles, list) or not profiles:
            msg = f"{where}: must be a non-empty list of profile names"
            raise ManifestError(msg)
        for profile in profiles:
            if not isinstance(profile, str) or not _PROFILE.fullmatch(profile):
                msg = f"{where}: {profile!r} is not a DIGGS profile name"
                raise ManifestError(msg)
            extra.append(
                dataclasses.replace(by_key[key], key=f"{key}@{profile}", diggs_version=profile)
            )
    return [*entries, *extra]


def _check_url(url: str) -> None:
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.hostname not in ALLOWED_HOSTS:
        msg = f"refusing to download from {url!r}: only https://{sorted(ALLOWED_HOSTS)}"
        raise ManifestError(msg)


class _CheckedRedirectHandler(urllib.request.HTTPRedirectHandler):
    """Check every redirect target before it is contacted, not after."""

    def redirect_request(  # noqa: PLR0917 - signature fixed by urllib
        self,
        req: urllib.request.Request,
        fp: Any,
        code: int,
        msg: str,
        headers: Any,
        newurl: str,
    ) -> urllib.request.Request | None:
        _check_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _default_opener(url: str, timeout: float) -> _Response:
    opener = urllib.request.build_opener(_CheckedRedirectHandler())
    return opener.open(url, timeout=timeout)  # type: ignore[no-any-return]


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        Path(tmp).replace(path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _read_at_most(response: _Response, limit: int) -> bytes:
    """Read until EOF or ``limit`` bytes; one ``read(n)`` may return fewer than ``n``."""
    chunks: list[bytes] = []
    total = 0
    while total < limit:
        chunk = response.read(min(2**20, limit - total))
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
    return b"".join(chunks)


def is_present(entry: Entry) -> bool:
    """Return whether ``entry`` is on disk with the recorded digest."""
    return entry.path.is_file() and digest(entry.path.read_bytes()) == entry.sha256


class _TransientError(CorpusError):
    """A download that may succeed if tried again (cut short, or a network error)."""


def _download(entry: Entry, url: str, size: int, opener: Opener) -> bytes:
    try:
        with opener(url, TIMEOUT_S) as response:
            _check_url(response.geturl())
            data = _read_at_most(response, size + 1)
    except (OSError, http.client.HTTPException) as exc:
        msg = f"{entry.key}: download failed: {exc}"
        raise _TransientError(msg) from exc
    if len(data) < size:
        msg = f"{entry.key}: download is {len(data)} bytes, recorded size is {size}"
        raise _TransientError(msg)
    if len(data) > size:
        msg = f"{entry.key}: download is more than {size} bytes, recorded size is {size}"
        raise CorpusError(msg)
    return data


def fetch(
    entries: Iterable[Entry],
    opener: Opener = _default_opener,
    *,
    attempts: int = 3,
    sleep: Callable[[float], None] = time.sleep,
) -> list[str]:
    """Download every external entry that is missing or stale; return what was fetched.

    A download cut short, or a network error, is retried up to ``attempts`` times with
    exponential backoff. A disallowed URL, an oversize file or a wrong digest is not.

    Raises:
        ManifestError: A URL or redirect target is not an allowed HTTPS host.
        CorpusError: A download's size or digest differs from the manifest, or every
            attempt failed.
    """
    fetched = []
    for entry in entries:
        if entry.url is None or entry.size is None or is_present(entry):
            continue
        _check_url(entry.url)
        for attempt in range(1, attempts + 1):
            try:
                data = _download(entry, entry.url, entry.size, opener)
                break
            except _TransientError as exc:
                if attempt == attempts:
                    raise CorpusError(f"{exc} (after {attempts} attempts)") from exc
                print(f"{exc}; retrying", file=sys.stderr)
                sleep(2.0**attempt)
        if digest(data) != entry.sha256:
            msg = f"{entry.key}: downloaded file does not match its recorded sha256"
            raise CorpusError(msg)
        _write_atomic(entry.path, data)
        fetched.append(entry.key)
    return fetched


def outcome(entry: Entry) -> dict[str, Any]:
    """Validate ``entry`` with pyDIGGS and return the parts that conformance compares."""
    import pydiggs  # noqa: PLC0415 - keep "fetch" usable without the package installed

    report = pydiggs.validate(entry.path, diggs_version=entry.diggs_version)
    rules: dict[str, set[str]] = {"error": set(), "warning": set()}
    for finding in report.findings:
        if finding.severity.value in rules:
            rules[finding.severity.value].add(finding.rule_id)
    counts = report.counts
    return {
        "ok": report.ok,
        "errors": counts["error"],
        "warnings": counts["warning"],
        "error_rules": sorted(rules["error"]),
        "warning_rules": sorted(rules["warning"]),
    }


def _local(tag: str) -> str:
    return tag.rpartition("}")[2]


def relation_of(name: str) -> str:
    """Return the link relation for an element with ``xlink:href``, named ``name``.

    The relation is the element name without its ``Ref`` suffix, as diggs-model spells it.

    Examples:
        >>> relation_of("projectRef"), relation_of("samplingFeatureRef"), relation_of("Ref")
        ('project', 'samplingFeature', 'Ref')
        >>> relation_of("member")
        'member'
    """
    return name.removesuffix("Ref") or name


def table_shape(text: str | None, ts: str = " ", cs: str = ",") -> tuple[int, int]:
    """Return ``(rows, cells)`` of a ``dataValues`` text with tuple and cell separators.

    A whitespace tuple separator splits on any run of whitespace, since files wrap rows
    with newlines and indentation. Empty cells (``1,,3``) count.

    Examples:
        >>> table_shape("1,2,3 4,5,6")
        (2, 6)
        >>> table_shape("a;b|c;d", ts="|", cs=";")
        (2, 4)
        >>> table_shape(None), table_shape("   ")
        ((0, 0), (0, 0))
    """
    body = (text or "").strip()
    if not body:
        return 0, 0
    tuples = body.split() if ts.isspace() else [t.strip() for t in body.split(ts) if t.strip()]
    return len(tuples), sum(len(t.split(cs)) for t in tuples)


def census(entry: Entry) -> dict[str, Any]:
    """Count what a reader of ``entry`` must produce, from a whole-tree parse.

    Counts are by DIGGS local name, so they read the same for 2.5.a, 2.6 and 3.x:

    * ``members``: each child of the root as ``<property>/<element>`` (``-`` for a
      property with no element child, such as a by-reference member);
    * ``procedures``: the element inside every ``procedure``;
    * ``links``: every element with ``xlink:href``, by relation (:func:`relation_of`);
      ``links_unresolved`` counts ``#id`` targets not in the file, ``links_remote``
      every other target;
    * ``result_tables``: every ``*ResultSet`` (a ``gml:DataBlock``), with the rows and
      cells of its ``dataValues`` (:func:`table_shape`).

    A file a reader must refuse is recorded as ``readable = false`` with the
    ``DocumentError`` kind it must raise: ``malformed`` (not well-formed XML) or
    ``not-diggs`` (the root is not ``Diggs``).
    """
    from lxml import etree  # noqa: PLC0415 - keep "fetch" usable without the package

    from pydiggs import _xml, detect  # noqa: PLC0415

    try:
        tree = _xml.parse(entry.path)
    except etree.XMLSyntaxError:
        return {"readable": False, "document_error": "malformed"}
    root = tree.getroot()
    if _local(root.tag) != "Diggs":
        return {"readable": False, "document_error": "not-diggs"}
    members: Counter[str] = Counter()
    for child in root.iterchildren(tag=etree.Element):
        inner = next(child.iterchildren(tag=etree.Element), None)
        members[f"{_local(child.tag)}/{'-' if inner is None else _local(inner.tag)}"] += 1
    procedures: Counter[str] = Counter()
    links: Counter[str] = Counter()
    ids: Counter[str] = Counter()
    hrefs: list[str] = []
    counts = dict.fromkeys(("elements", "result_tables", "result_rows", "result_cells"), 0)
    for element in root.iter(tag=etree.Element):
        counts["elements"] += 1
        name = _local(element.tag)
        if (gml_id := element.get(_GML_ID)) is not None:
            ids[gml_id] += 1
        if (href := element.get(_XLINK_HREF)) is not None:
            links[relation_of(name)] += 1
            hrefs.append(href.strip())
        if name == "procedure":
            inner = next(element.iterchildren(tag=etree.Element), None)
            if inner is not None:
                procedures[_local(inner.tag)] += 1
        elif name.endswith("ResultSet"):
            counts["result_tables"] += 1
            for values in element.iter(tag=etree.Element):
                if _local(values.tag) == "dataValues":
                    rows, cells = table_shape(
                        values.text, values.get("ts", " "), values.get("cs", ",")
                    )
                    counts["result_rows"] += rows
                    counts["result_cells"] += cells
    return {
        "readable": True,
        "diggs_version": detect.detect_diggs_version(tree),
        **counts,
        "gml_ids": len(ids),
        "duplicate_gml_ids": sum(1 for n in ids.values() if n > 1),
        "links_unresolved": sum(1 for h in hrefs if h.startswith("#") and h[1:] not in ids),
        "links_remote": sum(1 for h in hrefs if h and not h.startswith("#")),
        "members": dict(sorted(members.items())),
        "procedures": dict(sorted(procedures.items())),
        "links": dict(sorted(links.items())),
    }


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def render_expected(outcomes: dict[str, dict[str, Any]], header: str = _HEADER) -> str:
    """Render outcomes as the text of ``expected.toml`` (sorted, stable).

    A field whose value is a dict becomes a sub-table, ``["<key>".<field>]``.
    """
    lines = [header]
    for key in sorted(outcomes):
        quoted = _toml_value(key)
        fields = outcomes[key]
        lines.append(f"\n[{quoted}]\n")
        lines.extend(
            f"{field} = {_toml_value(v)}\n"
            for field, v in fields.items()
            if not isinstance(v, dict)
        )
        for field, table in fields.items():
            if isinstance(table, dict):
                lines.append(f"\n[{quoted}.{field}]\n")
                lines.extend(f"{_toml_value(k)} = {_toml_value(v)}\n" for k, v in table.items())
    return "".join(lines)


def _require_present(entries: Sequence[Entry], *, allow_missing: bool) -> list[Entry]:
    """Return the entries on disk with their recorded digest.

    ``allow_missing`` skips only external files that have not been fetched. A corrupt
    file, or a missing vendored file, always fails.
    """
    ready: list[Entry] = []
    bad: list[Entry] = []
    for entry in entries:
        if is_present(entry):
            ready.append(entry)
        elif allow_missing and entry.url is not None and not entry.path.exists():
            print(f"not fetched, skipped: {entry.key}", file=sys.stderr)
        else:
            bad.append(entry)
    for entry in bad:
        hint = " (run: python scripts/conformance.py fetch)" if entry.url else ""
        print(f"missing or corrupt: {entry.key}{hint}", file=sys.stderr)
    if bad:
        msg = f"{len(bad)} corpus file(s) missing or corrupt"
        raise CorpusError(msg)
    return ready


Measure = Callable[[Entry], dict[str, Any]]


def record(entries: Sequence[Entry], expected: Path = EXPECTED, measure: Measure = outcome) -> int:
    """Measure every entry and rewrite ``expected``; return the number of files.

    ``measure`` is :func:`outcome` (validation) or :func:`census` (the reader census).
    """
    ready = _require_present(entries, allow_missing=False)
    header = _MODEL_HEADER if measure is census else _HEADER
    text = render_expected({e.key: measure(e) for e in ready}, header)
    expected.write_text(text, encoding="utf-8")
    return len(ready)


def check(
    entries: Sequence[Entry],
    expected: Path = EXPECTED,
    *,
    allow_missing: bool = False,
    measure: Measure = outcome,
) -> list[str]:
    """Compare pyDIGGS's outcomes with ``expected``; return one line per difference."""
    want = _load_toml(expected)
    ready = _require_present(entries, allow_missing=allow_missing)
    problems = [
        f"{key}: in {expected.name} but not in the corpus"
        for key in sorted(set(want) - {e.key for e in entries})
    ]
    for entry in ready:
        if entry.key not in want:
            problems.append(f"{entry.key}: no expected outcome (run record and review)")
            continue
        got = measure(entry)
        problems.extend(
            f"{entry.key}: {field} expected {want[entry.key].get(field)!r}, got {value!r}"
            for field, value in got.items()
            if want[entry.key].get(field) != value
        )
    return problems


# --- the AGS4 set ----------------------------------------------------------------------


def raw_sha256(path: Path) -> str:
    """Return the sha256 of the bytes of ``path``, with no normalisation.

    The oracle records this one: line endings matter to an AGS4 reader and to Rule 2a.
    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


def ags4_fixtures(fixtures: Path = AGS4_FIXTURES) -> list[Entry]:
    """Return the synthetic AGS4 fixtures as corpus entries keyed ``fixtures/<name>``.

    They are in the repository, so the digest (as :class:`Entry` defines it) is that of
    the file on disk.
    """
    if not fixtures.is_dir():
        return []
    return [
        Entry(f"fixtures/{path.name}", path, digest(path.read_bytes()))
        for path in sorted(fixtures.glob("*.ags"))
        if path.is_file()
    ]


def _rel(path: Path) -> str:
    """``path`` relative to the repository root, with ``/`` separators, if under it."""
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def check_ags4(
    entries: Sequence[Entry],
    expected: Path = AGS4_EXPECTED,
    *,
    allow_missing: bool = False,
) -> list[str]:
    """Compare the AGS4 set with the oracle record; return one line per difference.

    ``expected`` is ``conformance/ags4-expected.toml``, written by
    ``scripts/ags4_oracle.py record``. Every entry needs a ``[[file]]`` with its key, its
    path and the sha256 of the bytes it was recorded from; no record may name a file
    that is not in the set. What pyDIGGS reads is compared with the record by the
    pydiggs.ags4 tests, not here: this check needs neither python-ags4 nor pyDIGGS.
    """
    want = _load_toml(expected)
    records = want.get("file", [])
    if not isinstance(records, list) or not all(
        isinstance(r, dict) and isinstance(r.get("key"), str) for r in records
    ):
        msg = f"{expected.name}: [[file]] must be an array of tables, each with a key"
        raise ManifestError(msg)
    by_key = {r["key"]: r for r in records}
    ready = _require_present(entries, allow_missing=allow_missing)
    hint = f"run: {AGS4_ORACLE}"
    problems = [
        f"{key}: in {expected.name} but not in the AGS4 set"
        for key in sorted(set(by_key) - {e.key for e in entries})
    ]
    for entry in ready:
        record = by_key.get(entry.key)
        if record is None:
            problems.append(f"{entry.key}: no oracle record ({hint})")
        elif record.get("sha256") != raw_sha256(entry.path):
            problems.append(f"{entry.key}: changed since the oracle was recorded ({hint})")
        elif record.get("path") != _rel(entry.path):
            problems.append(
                f"{entry.key}: path expected {_rel(entry.path)!r}, got {record.get('path')!r}"
            )
    return problems


def _main_ags4(command: str, *, allow_missing: bool) -> int:
    external = load_external(AGS4_CORPUS, AGS4_CACHE)
    if command == "fetch":
        for key in fetch(external):
            print(f"fetched {key}")
        print(f"{len(external)} external AGS4 file(s) present")
        return 0
    if command == "record":
        print(f"error: the AGS4 set is recorded from python-ags4: {AGS4_ORACLE}", file=sys.stderr)
        return 2
    entries = [*external, *ags4_fixtures(AGS4_FIXTURES)]
    problems = check_ags4(entries, AGS4_EXPECTED, allow_missing=allow_missing)
    for line in problems:
        print(line)
    print(f"{len(entries)} AGS4 file(s), {len(problems)} difference(s)")
    return 1 if problems else 0


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=["fetch", "check", "record"])
    parser.add_argument(
        "--allow-missing", action="store_true", help="check: skip files not fetched"
    )
    parser.add_argument(
        "--model",
        action="store_true",
        help="check/record the reader census in model.toml instead of expected.toml",
    )
    parser.add_argument(
        "--set",
        choices=["diggs", "ags4"],
        default="diggs",
        help="the DIGGS corpus (corpus.toml, default) or the AGS4 set (ags4-corpus.toml)",
    )
    args = parser.parse_args(argv)
    if args.set == "ags4" and args.model:
        parser.error("--model is for the DIGGS corpus, not --set ags4")
    try:
        if args.set == "ags4":
            return _main_ags4(args.command, allow_missing=args.allow_missing)
        external = load_external(CORPUS, CACHE)
        if args.command == "fetch":
            for key in fetch(external):
                print(f"fetched {key}")
            print(f"{len(external)} external file(s) present")
            return 0
        base = [*load_vendored(VENDORED_PROVENANCE), *external]
        # The census does not depend on the validation profile, so it has no @profile rows.
        entries = base if args.model else with_profiles(base, CORPUS)
        target, measure = (MODEL, census) if args.model else (EXPECTED, outcome)
        if args.command == "record":
            print(f"recorded {record(entries, target, measure)} file(s) in {target.name}")
            return 0
        problems = check(entries, target, allow_missing=args.allow_missing, measure=measure)
    except CorpusError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2 if isinstance(exc, ManifestError) else 1
    for line in problems:
        print(line)
    print(f"{len(entries)} corpus file(s), {len(problems)} difference(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
