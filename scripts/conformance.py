"""Fetch, record and check the pyDIGGS conformance corpus.

The conformance corpus is every DIGGS file pyDIGGS is checked against, with the outcome
pyDIGGS is expected to give for each one. It has two parts:

* ``tests/fixtures/official/`` — DIGGSml example files vendored into the repository
  (provenance in that folder's ``PROVENANCE.toml``, maintained by
  ``scripts/sync_reference.py``).
* External files listed in ``conformance/corpus.toml`` — real-world files from other
  projects, pinned by commit and sha256, fetched on demand into ``.cache/conformance/``.
  They are never committed and never packaged.

A file can also be checked under other DIGGS profiles, listed in ``corpus.toml``'s
``[profiles]`` table (for example the experimental ``3.1-dev``). Each is recorded
separately as ``<key>@<profile>``, next to the outcome under the detected profile.

Expected outcomes live in ``conformance/expected.toml``: for each file, the verdict, the
error and warning counts, and the distinct error and warning rule ids. ``record``
generates it; review the diff like a golden file before committing it. Other
implementations (DXplorer, the official pipeline) can be compared with the same file.

Usage (from the repository root)::

    # Download the external files (network: raw.githubusercontent.com only).
    python scripts/conformance.py fetch

    # Compare pyDIGGS's results with conformance/expected.toml (offline; CI runs this).
    python scripts/conformance.py check

    # Rewrite conformance/expected.toml from pyDIGGS's current results.
    python scripts/conformance.py record

Exit codes: 0 success, 1 a mismatch or a missing or corrupt file, 2 a bad manifest or
usage error.
"""

from __future__ import annotations

import argparse
import dataclasses
import hashlib
import http.client
import os
import re
import sys
import tempfile
import time
import tomllib
import urllib.parse
import urllib.request
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "conformance" / "corpus.toml"
EXPECTED = ROOT / "conformance" / "expected.toml"
VENDORED = ROOT / "tests" / "fixtures" / "official"
VENDORED_PROVENANCE = VENDORED / "PROVENANCE.toml"
CACHE = ROOT / ".cache" / "conformance"

# External files are downloaded from this host only, over HTTPS, at a pinned commit.
ALLOWED_HOSTS = frozenset({"raw.githubusercontent.com"})
MAX_BYTES = 64 * 2**20
TIMEOUT_S = 60.0

_HEX40 = re.compile(r"[0-9a-f]{40}")
_HEX64 = re.compile(r"[0-9a-f]{64}")
_GITHUB_REPO = re.compile(r"https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)")
# Every component of a corpus path must match this (no "..", no separators, no streams).
_SAFE_COMPONENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9._ +-]*")
# A DIGGS profile name, as pydiggs spells them (2.5.a, 2.6, 3.0.0, 3.1-dev).
_PROFILE = re.compile(r"[0-9][0-9A-Za-z.-]{0,31}")
_HEADER = (
    "# Expected pyDIGGS outcome for every conformance corpus file.\n"
    "# Generated by scripts/conformance.py record. Review changes like a golden file.\n"
)


class CorpusError(Exception):
    """A corpus file is missing, too large, or does not match its digest (exit 1)."""


class ManifestError(CorpusError):
    """A manifest is malformed or names a disallowed source (exit 2)."""


class _Response(Protocol):
    def read(self, amt: int = ..., /) -> bytes: ...  # pragma: no cover - protocol

    def geturl(self) -> str: ...  # pragma: no cover - protocol

    def __enter__(self) -> _Response: ...  # pragma: no cover - protocol

    def __exit__(self, *exc: object) -> None: ...  # pragma: no cover - protocol


Opener = Callable[[str, float], _Response]


@dataclass(frozen=True)
class Entry:
    """One corpus file.

    Attributes:
        key: Stable corpus id, ``official/<rel>`` or ``<source>/<rel>``.
        path: Where the file is (or will be) on disk.
        sha256: Digest after CRLF -> LF normalisation.
        url: Download URL for external files; ``None`` for vendored ones.
        size: Expected size in bytes for external files; ``None`` for vendored ones.
        diggs_version: Profile to validate with; ``None`` lets pyDIGGS detect it.
    """

    key: str
    path: Path
    sha256: str
    url: str | None = None
    size: int | None = None
    diggs_version: str | None = None


def digest(data: bytes) -> str:
    r"""Return the sha256 of ``data`` after CRLF -> LF normalisation.

    Matches ``scripts/sync_reference.py``, so a checkout with ``core.autocrlf`` verifies.

    Examples:
        >>> digest(b"a\r\nb") == digest(b"a\nb")
        True
    """
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def _safe_rel(rel: str, where: str) -> str:
    parts = rel.split("/")
    if not parts or any(not _SAFE_COMPONENT.fullmatch(p) or p in {".", ".."} for p in parts):
        msg = f"{where}: unsafe path {rel!r}"
        raise ManifestError(msg)
    return rel


def _require(table: dict[str, Any], key: str, where: str) -> Any:
    if key not in table:
        msg = f"{where}: missing {key!r}"
        raise ManifestError(msg)
    return table[key]


def _load_toml(path: Path) -> dict[str, Any]:
    """Parse a manifest; an unreadable or malformed file is a :class:`ManifestError`."""
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        msg = f"{path.name}: {exc}"
        raise ManifestError(msg) from exc


def load_vendored(provenance: Path = VENDORED_PROVENANCE) -> list[Entry]:
    """Return the vendored official examples as corpus entries."""
    data = _load_toml(provenance)
    base = provenance.parent
    entries = []
    for rel, meta in sorted(data.get("files", {}).items()):
        where = f"{provenance.name} [{rel}]"
        sha = str(_require(meta, "sha256", where))
        if not _HEX64.fullmatch(sha):
            msg = f"{where}: sha256 is not 64 lowercase hex digits"
            raise ManifestError(msg)
        entries.append(Entry(f"official/{_safe_rel(rel, where)}", base / rel, sha))
    return entries


def load_external(corpus: Path = CORPUS, cache: Path = CACHE) -> list[Entry]:
    """Return the external files listed in ``corpus`` as corpus entries."""
    data = _load_toml(corpus)
    sources: dict[str, tuple[str, str, str]] = {}
    for name, meta in data.get("sources", {}).items():
        where = f"{corpus.name} [sources.{name}]"
        _safe_rel(name, where)
        repo = str(_require(meta, "repo", where))
        commit = str(_require(meta, "commit", where))
        _require(meta, "license", where)
        match = _GITHUB_REPO.fullmatch(repo)
        if match is None:
            msg = f"{where}: repo must be https://github.com/<owner>/<name>"
            raise ManifestError(msg)
        if not _HEX40.fullmatch(commit):
            msg = f"{where}: commit must be a full 40-character sha"
            raise ManifestError(msg)
        sources[name] = (match.group(1), match.group(2), commit)

    entries = []
    for key, meta in sorted(data.get("files", {}).items()):
        where = f"{corpus.name} [files.{key!r}]"
        source, _, rel = key.partition("/")
        if source not in sources:
            msg = f"{where}: key must start with a declared source name"
            raise ManifestError(msg)
        _safe_rel(rel, where)
        upstream = _safe_rel(str(_require(meta, "path", where)), where)
        sha = str(_require(meta, "sha256", where))
        size = _require(meta, "size", where)
        if not _HEX64.fullmatch(sha):
            msg = f"{where}: sha256 is not 64 lowercase hex digits"
            raise ManifestError(msg)
        if not isinstance(size, int) or not 0 < size <= MAX_BYTES:
            msg = f"{where}: size must be an integer between 1 and {MAX_BYTES}"
            raise ManifestError(msg)
        owner, name, commit = sources[source]
        url = (
            f"https://raw.githubusercontent.com/{owner}/{name}/{commit}/"
            f"{urllib.parse.quote(upstream)}"
        )
        version = meta.get("diggs_version")
        entries.append(
            Entry(
                key, cache / source / rel, sha, url, size, None if version is None else str(version)
            )
        )
    return entries


def with_profiles(entries: Sequence[Entry], corpus: Path = CORPUS) -> list[Entry]:
    """Return ``entries`` plus one entry per extra profile in ``corpus``'s ``[profiles]``.

    ``[profiles]`` maps a corpus key to a list of DIGGS profiles. Each becomes an entry
    keyed ``<key>@<profile>`` for the same file, validated with that profile.
    """
    table = _load_toml(corpus).get("profiles", {})
    if not isinstance(table, dict):
        msg = f"{corpus.name} [profiles]: must be a table"
        raise ManifestError(msg)
    by_key = {e.key: e for e in entries}
    extra: list[Entry] = []
    for key, profiles in sorted(table.items()):
        where = f"{corpus.name} [profiles] {key!r}"
        if key not in by_key:
            msg = f"{where}: not a corpus file"
            raise ManifestError(msg)
        if not isinstance(profiles, list) or not profiles:
            msg = f"{where}: must be a non-empty list of profile names"
            raise ManifestError(msg)
        for profile in profiles:
            if not isinstance(profile, str) or not _PROFILE.fullmatch(profile):
                msg = f"{where}: {profile!r} is not a DIGGS profile name"
                raise ManifestError(msg)
            extra.append(
                dataclasses.replace(by_key[key], key=f"{key}@{profile}", diggs_version=profile)
            )
    return [*entries, *extra]


def _check_url(url: str) -> None:
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.hostname not in ALLOWED_HOSTS:
        msg = f"refusing to download from {url!r}: only https://{sorted(ALLOWED_HOSTS)}"
        raise ManifestError(msg)


class _CheckedRedirectHandler(urllib.request.HTTPRedirectHandler):
    """Check every redirect target before it is contacted, not after."""

    def redirect_request(  # noqa: PLR0917 - signature fixed by urllib
        self,
        req: urllib.request.Request,
        fp: Any,
        code: int,
        msg: str,
        headers: Any,
        newurl: str,
    ) -> urllib.request.Request | None:
        _check_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _default_opener(url: str, timeout: float) -> _Response:
    opener = urllib.request.build_opener(_CheckedRedirectHandler())
    return opener.open(url, timeout=timeout)  # type: ignore[no-any-return]


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        Path(tmp).replace(path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _read_at_most(response: _Response, limit: int) -> bytes:
    """Read until EOF or ``limit`` bytes; one ``read(n)`` may return fewer than ``n``."""
    chunks: list[bytes] = []
    total = 0
    while total < limit:
        chunk = response.read(min(2**20, limit - total))
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
    return b"".join(chunks)


def is_present(entry: Entry) -> bool:
    """Return whether ``entry`` is on disk with the recorded digest."""
    return entry.path.is_file() and digest(entry.path.read_bytes()) == entry.sha256


class _TransientError(CorpusError):
    """A download that may succeed if tried again (cut short, or a network error)."""


def _download(entry: Entry, url: str, size: int, opener: Opener) -> bytes:
    try:
        with opener(url, TIMEOUT_S) as response:
            _check_url(response.geturl())
            data = _read_at_most(response, size + 1)
    except (OSError, http.client.HTTPException) as exc:
        msg = f"{entry.key}: download failed: {exc}"
        raise _TransientError(msg) from exc
    if len(data) < size:
        msg = f"{entry.key}: download is {len(data)} bytes, recorded size is {size}"
        raise _TransientError(msg)
    if len(data) > size:
        msg = f"{entry.key}: download is more than {size} bytes, recorded size is {size}"
        raise CorpusError(msg)
    return data


def fetch(
    entries: Iterable[Entry],
    opener: Opener = _default_opener,
    *,
    attempts: int = 3,
    sleep: Callable[[float], None] = time.sleep,
) -> list[str]:
    """Download every external entry that is missing or stale; return what was fetched.

    A download cut short, or a network error, is retried up to ``attempts`` times with
    exponential backoff. A disallowed URL, an oversize file or a wrong digest is not.

    Raises:
        ManifestError: A URL or redirect target is not an allowed HTTPS host.
        CorpusError: A download's size or digest differs from the manifest, or every
            attempt failed.
    """
    fetched = []
    for entry in entries:
        if entry.url is None or entry.size is None or is_present(entry):
            continue
        _check_url(entry.url)
        for attempt in range(1, attempts + 1):
            try:
                data = _download(entry, entry.url, entry.size, opener)
                break
            except _TransientError as exc:
                if attempt == attempts:
                    raise CorpusError(f"{exc} (after {attempts} attempts)") from exc
                print(f"{exc}; retrying", file=sys.stderr)
                sleep(2.0**attempt)
        if digest(data) != entry.sha256:
            msg = f"{entry.key}: downloaded file does not match its recorded sha256"
            raise CorpusError(msg)
        _write_atomic(entry.path, data)
        fetched.append(entry.key)
    return fetched


def outcome(entry: Entry) -> dict[str, Any]:
    """Validate ``entry`` with pyDIGGS and return the parts that conformance compares."""
    import pydiggs  # noqa: PLC0415 - keep "fetch" usable without the package installed

    report = pydiggs.validate(entry.path, diggs_version=entry.diggs_version)
    rules: dict[str, set[str]] = {"error": set(), "warning": set()}
    for finding in report.findings:
        if finding.severity.value in rules:
            rules[finding.severity.value].add(finding.rule_id)
    counts = report.counts
    return {
        "ok": report.ok,
        "errors": counts["error"],
        "warnings": counts["warning"],
        "error_rules": sorted(rules["error"]),
        "warning_rules": sorted(rules["warning"]),
    }


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def render_expected(outcomes: dict[str, dict[str, Any]]) -> str:
    """Render outcomes as the text of ``expected.toml`` (sorted, stable)."""
    lines = [_HEADER]
    for key in sorted(outcomes):
        lines.append(f"\n[{_toml_value(key)}]\n")
        lines.extend(f"{field} = {_toml_value(v)}\n" for field, v in outcomes[key].items())
    return "".join(lines)


def _require_present(entries: Sequence[Entry], *, allow_missing: bool) -> list[Entry]:
    """Return the entries on disk with their recorded digest.

    ``allow_missing`` skips only external files that have not been fetched. A corrupt
    file, or a missing vendored file, always fails.
    """
    ready: list[Entry] = []
    bad: list[Entry] = []
    for entry in entries:
        if is_present(entry):
            ready.append(entry)
        elif allow_missing and entry.url is not None and not entry.path.exists():
            print(f"not fetched, skipped: {entry.key}", file=sys.stderr)
        else:
            bad.append(entry)
    for entry in bad:
        hint = " (run: python scripts/conformance.py fetch)" if entry.url else ""
        print(f"missing or corrupt: {entry.key}{hint}", file=sys.stderr)
    if bad:
        msg = f"{len(bad)} corpus file(s) missing or corrupt"
        raise CorpusError(msg)
    return ready


def record(entries: Sequence[Entry], expected: Path = EXPECTED) -> int:
    """Validate every entry and rewrite ``expected``; return the number of files."""
    ready = _require_present(entries, allow_missing=False)
    expected.write_text(render_expected({e.key: outcome(e) for e in ready}), encoding="utf-8")
    return len(ready)


def check(
    entries: Sequence[Entry], expected: Path = EXPECTED, *, allow_missing: bool = False
) -> list[str]:
    """Compare pyDIGGS's outcomes with ``expected``; return one line per difference."""
    want = _load_toml(expected)
    ready = _require_present(entries, allow_missing=allow_missing)
    problems = [
        f"{key}: in expected.toml but not in the corpus"
        for key in sorted(set(want) - {e.key for e in entries})
    ]
    for entry in ready:
        if entry.key not in want:
            problems.append(f"{entry.key}: no expected outcome (run record and review)")
            continue
        got = outcome(entry)
        problems.extend(
            f"{entry.key}: {field} expected {want[entry.key].get(field)!r}, got {value!r}"
            for field, value in got.items()
            if want[entry.key].get(field) != value
        )
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=["fetch", "check", "record"])
    parser.add_argument(
        "--allow-missing", action="store_true", help="check: skip files not fetched"
    )
    args = parser.parse_args(argv)
    try:
        external = load_external(CORPUS, CACHE)
        if args.command == "fetch":
            for key in fetch(external):
                print(f"fetched {key}")
            print(f"{len(external)} external file(s) present")
            return 0
        entries = with_profiles([*load_vendored(VENDORED_PROVENANCE), *external], CORPUS)
        if args.command == "record":
            print(f"recorded {record(entries, EXPECTED)} file(s) in {EXPECTED.name}")
            return 0
        problems = check(entries, EXPECTED, allow_missing=args.allow_missing)
    except CorpusError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2 if isinstance(exc, ManifestError) else 1
    for line in problems:
        print(line)
    print(f"{len(entries)} corpus file(s), {len(problems)} difference(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
