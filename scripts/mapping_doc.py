"""Generate ``docs/convert-mapping.md`` from the bundled AGS4 to DIGGS mapping tables.

The mapping table is the reviewable heart of the converter, so its documentation page is
made from it, never written by hand: one row per AGS4 heading (its target, the group's
review status, and the reason when it is not converted), then the unit and code tables.

Usage (from the package root)::

    python scripts/mapping_doc.py            # rewrite docs/convert-mapping.md
    python scripts/mapping_doc.py --check    # exit 1 when the committed page is stale

``tests/test_convert_mapping.py`` runs the check, so CI fails on a stale page.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from pydiggs.convert._mapping import (  # noqa: E402
    PROPERTIES_URL,
    GroupRule,
    HeadingRule,
    MappingTable,
    load_mapping,
)

PAGE = ROOT / "docs" / "convert-mapping.md"

_INTRO = """\
<!-- Generated by scripts/mapping_doc.py from src/pydiggs/convert/mappings/. Do not edit. -->

# AGS4 to DIGGS mapping (preview)

!!! warning "Preview: every group is a draft"
    This is mapping table **{version}**, used by `pydiggs.preview.convert.ags4_to_diggs`
    in pyDIGGS 1.9 and 1.10. Every group mapping is a draft until it is reviewed; mapping table 1.0
    is signed off with pyDIGGS 1.11, and until then a heading may move. Corrections from
    DIGGS and AGS practitioners are welcome: a mapping change is a small diff to the TOML
    files under `src/pydiggs/convert/mappings/`.

The converter writes DIGGS {diggs}. It reads AGS4 {ags}. No published AGS4 to DIGGS mapping
exists, so this table is original work. It holds only AGS4 group and heading names, keys
and parent groups; it copies nothing else from the AGS4 data dictionary.

Every non-null value of an AGS4 file is either carried into DIGGS or named by a
`convert` finding (see [Findings](findings.md#rule-ids)). A group that is not listed here
is reported as `convert.unmapped-group`; a heading that is listed as *not converted*, or
not listed at all, as `convert.unmapped-heading`; and anything the file's own `DICT`
group defines as `convert.user-defined`.

**Targets.** *key*: identifies the record; it becomes the `gml:id` (made a valid XML id)
and the `gml:name`. *link*: a key of the parent record, used to attach this record to it.
*field*: a value the converter places itself (named in the table). *param*: a DIGGS
element, as `Element/child`; a *measure* is written only with a unit DIGGS 3.0.0 allows
for it, and is reported otherwise. *column*: a result column, named by its key in the
[DIGGS property dictionary]({properties}). *format*: AGS4 format information the
converter reads; it is not data. *not converted*: with the reason.

Values are carried as reported. Units are renamed only through the unit table, and
nothing is converted numerically.
"""


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def _target(heading: HeadingRule) -> str:
    if heading.to == "column":
        return f"column `{heading.property}`"
    if heading.to in ("format", "none"):
        word = "format" if heading.to == "format" else "not converted"
        return f"{word}: {_escape(heading.reason or '')}"
    if heading.quantity is not None:
        return f"{heading.to} `{heading.target}` ({heading.quantity} measure)"
    return f"{heading.to} `{heading.target}`"


def _group(group: GroupRule) -> list[str]:
    facts = [f"pattern `{group.pattern}`", f"status **{group.status}**"]
    if group.keys:
        facts.append("keys " + ", ".join(f"`{key}`" for key in group.keys))
    if group.parent:
        facts.append(f"parent `{group.parent}`")
    if group.element:
        facts.append(f"DIGGS `{group.element}`")
    if group.procedure:
        facts.append(f"procedure `{group.procedure}`")
    if group.data:
        facts.append(f"data group `{group.data}`")
    for name, value in group.procedure_params.items():
        facts.append(f"`{name}` = `{value}`")
    lines = [f"## {group.name}", "", "; ".join(facts) + ".", ""]
    lines += ["| AGS4 heading | DIGGS target | Status |", "|---|---|---|"]
    for heading in group.headings.values():
        lines.append(f"| `{heading.name}` | {_target(heading)} | {group.status} |")
    return [*lines, ""]


def render(mapping: MappingTable) -> str:
    """The page for ``mapping``."""
    lines = [
        _INTRO.format(
            version=mapping.mapping_version,
            diggs=", ".join(mapping.diggs_versions),
            ags=", ".join(mapping.ags_versions),
            properties=PROPERTIES_URL,
        )
    ]
    for group in mapping.groups.values():
        lines += _group(group)
    lines += [
        "## Units",
        "",
        "An AGS4 unit with no row here is reported as `convert.unmapped-unit`.",
        "",
        "| AGS4 unit | DIGGS unit |",
        "|---|---|",
    ]
    lines += [f"| `{ags}` | `{diggs}` |" for ags, diggs in mapping.units.items()]
    lines += [
        "",
        "## Codes",
        "",
        "An AGS4 code with no row here, or with no DIGGS code, is reported as"
        " `convert.unmapped-code`.",
        "",
        "| AGS4 heading | AGS4 code | DIGGS element | DIGGS code |",
        "|---|---|---|---|",
    ]
    for rule in mapping.codes.values():
        code = f"`{rule.code}` ({rule.code_list})" if rule.code else ""
        if not code and rule.exact:
            code = "the element itself"
        element = f"`{rule.element}`" if rule.element else ""
        lines.append(f"| `{rule.heading}` | `{_escape(rule.ags)}` | {element} | {code} |")
    lines += [
        "",
        "## Coordinate reference systems",
        "",
        "`LOCA_GREF` names the CRS of `LOCA_NATE` and `LOCA_NATN`; `EPSG:<number>` is read"
        " as that EPSG code. `LOCA_LLZ` names the datum of `LOCA_LAT` and `LOCA_LON`. Any"
        " other value is reported, and nothing is guessed from the coordinates. Grid"
        " coordinates and ground levels are written only in the unit of the CRS's axes.",
        "",
        "| AGS4 heading | AGS4 value | DIGGS srsName | Axis unit |",
        "|---|---|---|---|",
    ]
    for (heading, ags), srs in mapping.crs.items():
        unit = mapping.crs_units.get(srs) if heading == "LOCA_GREF" else None
        shown = f"`{unit}`" if unit else ""
        lines.append(f"| `{heading}` | `{_escape(ags)}` | `{srs}` | {shown} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the page, or with ``--check`` verify it; return the process exit code."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify the page; write nothing")
    args = parser.parse_args(argv)
    text = render(load_mapping())
    if args.check:
        current = PAGE.read_text("utf-8") if PAGE.is_file() else ""
        if current != text:
            print(f"{PAGE.relative_to(ROOT)} is stale; run python scripts/mapping_doc.py")
            return 1
        print("mapping page OK")
        return 0
    if PAGE.is_file() and PAGE.read_text("utf-8") == text:
        print("mapping page unchanged")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
