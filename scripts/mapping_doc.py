"""Generate ``docs/convert-mapping.md`` from the bundled AGS4 and DIGGS mapping tables.

The mapping table is the reviewable heart of the converter, so its documentation page is
made from it, never written by hand: one row per AGS4 heading (its target, the group's
review status, and the reason when it is not converted), then the unit and code tables.

Usage (from the package root)::

    python scripts/mapping_doc.py            # rewrite docs/convert-mapping.md
    python scripts/mapping_doc.py --check    # exit 1 when the committed page is stale

``tests/test_convert_mapping.py`` runs the check, so CI fails on a stale page.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from pydiggs.convert._mapping import (  # noqa: E402
    PROPERTIES_URL,
    GroupRule,
    HeadingRule,
    MappingTable,
    load_mapping,
)

PAGE = ROOT / "docs" / "convert-mapping.md"

_INTRO = """\
<!-- Generated by scripts/mapping_doc.py from src/pydiggs/convert/mappings/. Do not edit. -->

# AGS4 and DIGGS mapping

!!! note "Mapping table {version}: {reviewed} of {groups} groups reviewed"
    This is mapping table **{version}**, used by `pydiggs.convert` in both directions:
    `ags4_to_diggs`, and `diggs_to_ags4` and `model_to_ags4`. A group's status is
    *draft* until its rows have been reviewed, and *reviewed* after. Changing where a
    heading goes is a new major version of the table; adding groups, headings or codes is a
    minor one. Corrections from DIGGS and AGS practitioners are welcome: a mapping change
    is a small diff to the TOML files under `src/pydiggs/convert/mappings/`.

The converter writes DIGGS {diggs}. It reads AGS4 {ags}, and writes AGS4 4.2 (the
default) or 4.1.1. As of November 2026 the BGS AGS validator (agsapi.bgs.ac.uk) and
python-ags4 1.2.0 accept AGS4 only up to 4.1.1: write `ags_version="4.1.1"` for files
meant for them. No published AGS4 to DIGGS mapping exists, so this table is original
work. It holds only AGS4 group and heading names, keys and parent groups; it copies
nothing else from the AGS4 data dictionary.

One table drives both directions: DIGGS to AGS4 writes each heading from the DIGGS value
it is read into below, and reports every DIGGS value with no heading here as
`convert.unmapped-element`. A heading marked `to-diggs` is used only from AGS4 to DIGGS,
one marked `to-ags4` only the other way. pyDIGGS bundles no AGS4 data dictionary, so the
TYPE of each heading it writes is the one its values have.

Every non-null value of an AGS4 file is either carried into DIGGS or named by a
`convert` finding (see [Findings](findings.md#rule-ids)). A group that is not listed here
is reported as `convert.unmapped-group`; a heading that is listed as *not converted*, or
not listed at all, as `convert.unmapped-heading`; and anything the file's own `DICT`
group defines as `convert.user-defined`.

**Targets.** *key*: identifies the record; it becomes the `gml:id` (made a valid XML id)
and the `gml:name`. *link*: a key of the parent record, used to attach this record to it.
*field*: a value the converter places itself (named in the table). *param*: a DIGGS
element, as `Element/child`; a *measure* is written only with a unit DIGGS 3.0.0 allows
for it, and is reported otherwise. *column*: a result column, named by its key in the
[DIGGS property dictionary]({properties}). *format*: AGS4 format information the
converter reads; it is not data. *not converted*: with the reason.

Values are carried as reported. Units are renamed only through the unit table, and
nothing is converted numerically.
"""


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def _target(heading: HeadingRule) -> str:
    if heading.to == "column":
        return f"column `{heading.property}`"
    if heading.to in ("format", "none"):
        word = "format" if heading.to == "format" else "not converted"
        return f"{word}: {_escape(heading.reason or '')}"
    if heading.quantity is not None:
        return f"{heading.to} `{heading.target}` ({heading.quantity} measure)"
    return f"{heading.to} `{heading.target}`"


_TOPS = {
    "previous-base": "each section starts at the base of the one above (the first at 0)",
    "surface": "each runs from the surface (0) to its depth",
}


def _component_facts(group: GroupRule) -> list[str]:
    """What the page says about a feature component, and the versions a group is written for."""
    facts = []
    if group.role:
        facts.append(f"held by the feature's `{group.holder_role or group.role}`")
    if group.holder:
        facts.append(f"inside a `{group.holder}`")
    if group.interval_top is not None:
        facts.append(_TOPS[group.interval_top])
    if group.to_ags4_versions is not None:
        facts.append("written for AGS4 " + ", ".join(group.to_ags4_versions))
    return facts


def _group(group: GroupRule) -> list[str]:
    facts = [f"pattern `{group.pattern}`", f"status **{group.status}**"]
    if group.keys:
        facts.append("keys " + ", ".join(f"`{key}`" for key in group.keys))
    if group.parent:
        facts.append(f"parent `{group.parent}`")
    if group.element:
        facts.append(f"DIGGS `{group.element}`")
    if group.procedure:
        facts.append(f"procedure `{group.procedure}`")
    if group.data:
        facts.append(f"data group `{group.data}`")
    facts += _component_facts(group)
    for name, value in group.procedure_params.items():
        facts.append(f"`{name}` = `{value}`")
    lines = [f"## {group.name}", "", "; ".join(facts) + ".", ""]
    lines += ["| AGS4 heading | DIGGS target | Status |", "|---|---|---|"]
    for heading in group.headings.values():
        target = _target(heading)
        if heading.direction != "both":
            target += f" ({heading.direction} only)"
        lines.append(f"| `{heading.name}` | {target} | {group.status} |")
    return [*lines, ""]


def render(mapping: MappingTable) -> str:
    """The page for ``mapping``."""
    lines = [
        _INTRO.format(
            version=mapping.mapping_version,
            diggs=", ".join(mapping.diggs_versions),
            ags=", ".join(mapping.ags_versions),
            properties=PROPERTIES_URL,
            groups=len(mapping.groups),
            reviewed=sum(1 for g in mapping.groups.values() if g.status == "reviewed"),
        )
    ]
    for group in mapping.groups.values():
        lines += _group(group)
    lines += [
        "## Units",
        "",
        "An AGS4 unit with no row here is reported as `convert.unmapped-unit`.",
        "",
        "| AGS4 unit | DIGGS unit |",
        "|---|---|",
    ]
    lines += [f"| `{ags}` | `{diggs}` |" for ags, diggs in mapping.units.items()]
    lines += [
        "",
        "## Codes",
        "",
        "An AGS4 code with no row here, or with no DIGGS code, is reported as"
        " `convert.unmapped-code`. Codes are matched as AGS4 says abbreviations are, not"
        " case sensitive, and a value joined by the file's `TRAN_RCON` (`+` by default)"
        " matches the row that joins the same codes in either order. Where two AGS4 codes"
        " share one DIGGS code, DIGGS to AGS4 writes the first; a value matching a later"
        " row is written as the DIGGS code and the AGS4 code is reported.",
        "",
        "| AGS4 heading | AGS4 code | DIGGS element | DIGGS code |",
        "|---|---|---|---|",
    ]
    for rule in mapping.codes.values():
        code = f"`{rule.code}` ({rule.code_list})" if rule.code else ""
        if not code and rule.exact:
            code = "the element itself"
        element = f"`{rule.element}`" if rule.element else ""
        lines.append(f"| `{rule.heading}` | `{_escape(rule.ags)}` | {element} | {code} |")
    lines += [
        "",
        "## Coordinate reference systems",
        "",
        "`LOCA_GREF` names the CRS of `LOCA_NATE` and `LOCA_NATN`; `EPSG:<number>` is read"
        " as that EPSG code, and an AGS4 4.2 `LOCA_NSRI` (an EPSG code) is read before"
        " `LOCA_GREF`, which is reported when it disagrees. `LOCA_LLZ` names the datum of"
        " `LOCA_LAT` and `LOCA_LON`, and a 4.2 `LOCA_LLSI` is read before it. Any other"
        " value is reported, and nothing is guessed from the coordinates. Grid"
        " coordinates and ground levels are written only in the unit of the CRS's axes. A"
        " ground level is written as the third coordinate: in the compound CRS a"
        " `LOCA_NATD` row gives with its horizontal CRS, and otherwise in the grid CRS,"
        " which does not state the level's vertical datum (reported as `convert.assumed`)."
        " Values are matched not case sensitively. DIGGS to AGS4 writes the first row of"
        " each CRS, and for AGS4 4.2 also `LOCA_NSRI` or `LOCA_LLSI`.",
        "",
        "| AGS4 heading | AGS4 value | DIGGS srsName | Axis unit | With horizontal CRS |",
        "|---|---|---|---|---|",
    ]
    for (heading, ags), srs in mapping.crs.items():
        unit = mapping.crs_units.get(srs) if heading != "LOCA_LLZ" else None
        shown = f"`{unit}`" if unit else ""
        base = mapping.crs_horizontal.get(srs) if heading == "LOCA_NATD" else None
        with_ = f"`{base}`" if base else ""
        lines.append(f"| `{heading}` | `{_escape(ags)}` | `{srs}` | {shown} | {with_} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the page, or with ``--check`` verify it; return the process exit code."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify the page; write nothing")
    args = parser.parse_args(argv)
    text = render(load_mapping())
    if args.check:
        current = PAGE.read_text("utf-8") if PAGE.is_file() else ""
        if current != text:
            print(f"{PAGE.relative_to(ROOT)} is stale; run python scripts/mapping_doc.py")
            return 1
        print("mapping page OK")
        return 0
    if PAGE.is_file() and PAGE.read_text("utf-8") == text:
        print("mapping page unchanged")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
