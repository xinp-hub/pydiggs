"""Record what python-ags4 makes of every file in the AGS4 set: the conformance oracle.

The oracle is **python-ags4 1.2.0** (PyPI ``python-ags4``, released 2026-03-25 and still
the latest release when checked on 2026-11-11; "GNU Lesser General Public License v3
(LGPLv3)" by its PyPI classifier, while the repository,
https://gitlab.com/ags-data-format-wg/ags-python-library, carries the GPL-3.0 text in
``LICENSE`` beside ``COPYING.LESSER``; run by the AGS Data Format Working Group). Either
reading is copyleft, and its caps (``pandas<3``, ``rich<14``) conflict with pyDIGGS's
lock, so it is never a dependency of pyDIGGS: not in ``pyproject.toml``, not in
``uv.lock``, never imported by the package, and no python-ags4 code is copied. It runs in
a throwaway environment, from the repository root, after fetching the external files::

    python scripts/conformance.py fetch --set ags4
    uv run --isolated --with python-ags4==1.2.0 python scripts/ags4_oracle.py record

(``uv run --isolated --no-project --with python-ags4==1.2.0 ...`` does the same without
installing pyDIGGS beside it; this script needs only the standard library and
python-ags4.) The tests load this file with a fake oracle; the real one is imported only
by :func:`python_ags4_oracle`, when ``record`` runs.

``record`` reads every external file of ``conformance/ags4-corpus.toml`` and every
``tests/fixtures/ags4/*.ags`` with python-ags4, runs its rule check on each, and rewrites
``conformance/ags4-expected.toml``. Review the diff like a golden file. Its shape::

    [oracle]
    name = "python-ags4"
    version = "1.2.0"
    pandas = "2.3.3"

    [[file]]
    key = "bgs/161-41.ags"            # corpus key, or "fixtures/<name>"
    path = ".cache/conformance/ags4/bgs/161-41.ags"   # from the repository root
    sha256 = "..."                    # of the bytes read, not normalised
    size = 2583
    encoding = "utf-8"                # utf-8, utf-8-sig, or cp1252 (Q8's fallback)
    ags_version = "4.0"               # TRAN_AGS of the first TRAN row, "" if none
    readable = true                   # false: python-ags4 refused it; see "error", group = []

    [[file.group]]                    # one per GROUP, in file order
    name = "PROJ"
    headings = ["PROJ_ID", ...]       # without the leading "HEADING"
    units = ["", ...]                 # the first UNIT row, [] if none
    types = ["ID", ...]               # the first TYPE row, [] if none
    row_count = 1                     # DATA rows
    rows_sha256 = "..."               # see rows_digest()
    rows = [["..."], ...]             # only for files in the repository (fixtures)

    [file.check]                      # python-ags4's check_file, standard dictionary
    dictionary = "Standard_dictionary_v4_0_4.ags"
    errors = 3                        # python-ags4's own error count
    fyi = 0

    [file.check.rules]                # rule id -> number of reports
    "ags4.rule-2a" = 2

    [file.check.lines]                # rule id -> first line numbers reported
    "ags4.rule-2a" = [1, 2]

Cell values of external files are not written, only their digest: the OGL that covers the
BGS files does not cover personal data, and the record need not republish it.

Exit codes: 0 success, 1 a missing or corrupt corpus file, 2 a bad manifest, usage, or a
python-ags4 that is missing or not the pinned version.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib
import importlib.util
import json
import logging
import re
import sys
import unicodedata
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Any

ORACLE_NAME = "python-ags4"
ORACLE_VERSION = "1.2.0"
#: How many line numbers are kept per rule; the count is always complete.
MAX_LINES = 20

_HERE = Path(__file__).resolve().parent
_RULE = re.compile(r"AGS Format Rule ([0-9]+[a-z]?)")
_HEADER = (
    "# What python-ags4 reads and reports for every file in the AGS4 conformance set.\n"
    "# Generated by scripts/ags4_oracle.py record (python-ags4 in an isolated environment).\n"
    "# Review changes like a golden file. Never edit by hand.\n"
)


def _conformance() -> ModuleType:
    """Load ``scripts/conformance.py`` (the manifest and fixture helpers) from beside us."""
    name = "conformance"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, _HERE / "conformance.py")
    if spec is None or spec.loader is None:  # pragma: no cover - the file is in the repo
        raise ImportError(name)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclasses resolve annotations through sys.modules
    try:
        spec.loader.exec_module(module)
    except BaseException:
        del sys.modules[name]
        raise
    return module


class OracleError(Exception):
    """python-ags4 is missing or is not the pinned version (exit 2)."""


@dataclass(frozen=True)
class Oracle:
    """The two python-ags4 calls the record needs, so a test can pass a fake.

    Attributes:
        version: python-ags4's version.
        pandas: pandas's version (python-ags4's results depend on it).
        read: ``AGS4_to_dict(path, encoding=..., rename_duplicate_headers=False)``,
            returning ``(data, headings)``.
        check: ``check_file(path, encoding=...)``, returning the error dict.
    """

    version: str
    pandas: str
    read: Callable[
        [Path, str], tuple[Mapping[str, Mapping[str, list[Any]]], Mapping[str, list[str]]]
    ]
    check: Callable[[Path, str], Mapping[str, list[Mapping[str, Any]]]]


def python_ags4_oracle() -> Oracle:
    """Return the real oracle; only ``record`` calls this, in the isolated environment."""
    try:
        ags4: Any = importlib.import_module("python_ags4.AGS4")
        pandas: Any = importlib.import_module("pandas")
        from importlib.metadata import version  # noqa: PLC0415

        found = version(ORACLE_NAME)
    except ImportError as exc:
        msg = (
            f"{ORACLE_NAME} is not installed; run: uv run --isolated --with "
            f"{ORACLE_NAME}=={ORACLE_VERSION} python scripts/ags4_oracle.py record"
        )
        raise OracleError(msg) from exc
    if found != ORACLE_VERSION:
        msg = f"{ORACLE_NAME} {found} is installed; the oracle is pinned to {ORACLE_VERSION}"
        raise OracleError(msg)

    def read(path: Path, encoding: str) -> Any:
        return ags4.AGS4_to_dict(str(path), encoding=encoding, rename_duplicate_headers=False)

    def check(path: Path, encoding: str) -> Any:
        return ags4.check_file(str(path), encoding=encoding)

    return Oracle(found, str(pandas.__version__), read, check)


def encoding_of(data: bytes) -> str:
    r"""Return the encoding to read ``data`` with, as pyDIGGS's reader decides it (Q8).

    UTF-8 (with or without a byte order mark), else Windows-1252.

    Examples:
        >>> encoding_of(b'"GROUP","PROJ"'), encoding_of("é".encode())
        ('utf-8', 'utf-8')
        >>> encoding_of(b'\xef\xbb\xbf"GROUP"'), encoding_of("é".encode("cp1252"))
        ('utf-8-sig', 'cp1252')
    """
    if data.startswith(b"\xef\xbb\xbf"):
        return "utf-8-sig"
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return "cp1252"
    return "utf-8"


def rows_digest(rows: Sequence[Sequence[str]]) -> str:
    """Return the digest of a group's DATA rows, as ``rows_sha256`` records it.

    The sha256 of the UTF-8 JSON of the rows (a list of lists of strings, without the
    leading ``"DATA"``), with ``ensure_ascii=False`` and no spaces. A reader under test
    computes the same from its own rows.

    Examples:
        >>> rows_digest([["BH01", "1.20"]]) == hashlib.sha256(b'[["BH01","1.20"]]').hexdigest()
        True
    """
    text = json.dumps([list(row) for row in rows], ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def rule_id(name: str) -> str | None:
    """Return the pyDIGGS rule id for a python-ags4 report key, or ``None``.

    Examples:
        >>> rule_id("AGS Format Rule 10a"), rule_id("AGS Format Rule 2")
        ('ags4.rule-10a', 'ags4.rule-2')
        >>> rule_id("FYI (Related to Rule 16)") is None
        True
    """
    match = _RULE.fullmatch(name)
    return None if match is None else f"ags4.rule-{match.group(1)}"


def groups_of(
    data: Mapping[str, Mapping[str, list[Any]]],
    headings: Mapping[str, list[str]],
    *,
    with_rows: bool,
) -> list[dict[str, Any]]:
    """Turn python-ags4's ``AGS4_to_dict`` result into the ``[[file.group]]`` records."""
    groups = []
    for name, columns in data.items():
        names = list(headings.get(name, ["HEADING"]))[1:]
        kinds = [str(k) for k in columns.get("HEADING", [])]
        table = [[str(v) for v in columns.get(h, [])] for h in names]

        def row(i: int, table: list[list[str]] = table) -> list[str]:
            return [column[i] for column in table]

        rows = [row(i) for i, kind in enumerate(kinds) if kind == "DATA"]
        units = next((row(i) for i, kind in enumerate(kinds) if kind == "UNIT"), [])
        types = next((row(i) for i, kind in enumerate(kinds) if kind == "TYPE"), [])
        group: dict[str, Any] = {
            "name": name,
            "headings": names,
            "units": units,
            "types": types,
            "row_count": len(rows),
            "rows_sha256": rows_digest(rows),
        }
        if with_rows:
            group["rows"] = rows
        groups.append(group)
    return groups


def _line_numbers(reports: Sequence[Mapping[str, Any]]) -> list[int]:
    lines = set()
    for report in reports:
        line = report.get("line")
        if isinstance(line, int) and not isinstance(line, bool):
            lines.add(line)
        elif isinstance(line, str) and line.isdigit():
            lines.add(int(line))
    return sorted(lines)[:MAX_LINES]


def summarise_check(errors: Mapping[str, Sequence[Mapping[str, Any]]]) -> dict[str, Any]:
    """Reduce python-ags4's ``check_file`` result to what rule parity compares.

    Rules become pyDIGGS ids with a count and their first line numbers. ``Metadata``
    (it holds a clock time) and ``Summary of data`` are dropped; the dictionary used is
    kept, and a ``Validator Process Error`` is kept as ``process_error``.
    """
    rules: dict[str, int] = {}
    lines: dict[str, list[int]] = {}
    errors_n = fyi = 0
    for key, reports in errors.items():
        if (rid := rule_id(key)) is not None:
            rules[rid] = len(reports)
            lines[rid] = _line_numbers(reports)
            errors_n += len(reports)
        elif key == "Validator Process Error":
            errors_n += len(reports)
        elif "FYI" in key:
            fyi += len(reports)
    meta = {str(r.get("line")): str(r.get("desc")) for r in errors.get("Metadata", [])}
    summary: dict[str, Any] = {
        "dictionary": meta.get("Dictionary", ""),
        "errors": errors_n,
        "fyi": fyi,
    }
    process = [str(r.get("desc", "")) for r in errors.get("Validator Process Error", [])]
    if process:
        summary["process_error"] = process[0][:300]
    order = sorted(rules, key=_rule_order)
    summary["rules"] = {r: rules[r] for r in order}
    summary["lines"] = {r: lines[r] for r in order if lines[r]}
    return summary


def _rule_order(rid: str) -> tuple[int, str]:
    number = rid.removeprefix("ags4.rule-")
    digits = number.rstrip("abcdefghijklmnopqrstuvwxyz")
    return int(digits or 0), number


def _ags_version(groups: Sequence[Mapping[str, Any]], data: Mapping[str, Any]) -> str:
    for group in groups:
        if group["name"] == "TRAN" and "TRAN_AGS" in group["headings"]:
            columns = data["TRAN"]
            for kind, value in zip(columns.get("HEADING", []), columns["TRAN_AGS"], strict=False):
                if kind == "DATA":
                    return str(value)
    return ""


def measure(key: str, path: Path, oracle: Oracle, *, in_repo: bool, rel: str) -> dict[str, Any]:
    """Read and check one file with the oracle; return its ``[[file]]`` record."""
    data_bytes = path.read_bytes()
    encoding = encoding_of(data_bytes)
    record: dict[str, Any] = {
        "key": key,
        "path": rel,
        "sha256": hashlib.sha256(data_bytes).hexdigest(),
        "size": len(data_bytes),
        "encoding": encoding,
    }
    try:
        data, headings = oracle.read(path, encoding)
    except Exception as exc:
        message = " ".join(str(exc).split())[:300] or type(exc).__name__
        record |= {"ags_version": "", "readable": False, "error": message, "group": []}
    else:
        groups = groups_of(data, headings, with_rows=in_repo)
        record |= {"ags_version": _ags_version(groups, data), "readable": True, "group": groups}
    record["check"] = summarise_check(oracle.check(path, encoding))
    return record


# --- TOML output ------------------------------------------------------------------------

_ESCAPES = {
    '"': '\\"',
    "\\": "\\\\",
    "\b": "\\b",
    "\t": "\\t",
    "\n": "\\n",
    "\f": "\\f",
    "\r": "\\r",
}


def toml_string(text: str) -> str:
    r"""Return ``text`` as a TOML basic string; control characters are escaped.

    Examples:
        >>> print(toml_string('a "b"\\\tc\x01'))
        "a \"b\"\\\tc\u0001"
    """
    out = []
    for char in text:
        if char in _ESCAPES:
            out.append(_ESCAPES[char])
        elif unicodedata.category(char) == "Cc":
            out.append(f"\\u{ord(char):04X}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def _value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, list):
        if value and isinstance(value[0], list):
            return "[\n" + "".join(f"  {_value(v)},\n" for v in value) + "]"
        return "[" + ", ".join(_value(v) for v in value) + "]"
    msg = f"cannot write {type(value).__name__} to TOML"
    raise TypeError(msg)


def _scalars(table: Mapping[str, Any]) -> list[str]:
    return [f"{k} = {_value(v)}\n" for k, v in table.items() if not isinstance(v, dict | tuple)]


def render(oracle: Oracle, records: Sequence[Mapping[str, Any]]) -> str:
    """Render the records as the text of ``ags4-expected.toml`` (sorted by key, stable)."""
    lines = [
        _HEADER,
        "\n[oracle]\n",
        f"name = {toml_string(ORACLE_NAME)}\n",
        f"version = {toml_string(oracle.version)}\n",
        f"pandas = {toml_string(oracle.pandas)}\n",
    ]
    for record in sorted(records, key=lambda r: str(r["key"])):
        lines.append("\n[[file]]\n")
        lines.extend(
            f"{k} = {_value(v)}\n" for k, v in record.items() if k not in {"group", "check"}
        )
        if not record["group"]:
            lines.append("group = []\n")  # so every [[file]] has a group array
        for group in record["group"]:
            lines.append("\n[[file.group]]\n")
            lines.extend(f"{k} = {_value(v)}\n" for k, v in group.items())
        check = record["check"]
        lines.append("\n[file.check]\n")
        lines.extend(_scalars(check))
        for sub in ("rules", "lines"):
            lines.append(f"\n[file.check.{sub}]\n")
            lines.extend(f"{toml_string(k)} = {_value(v)}\n" for k, v in check[sub].items())
    return "".join(lines)


def record(oracle: Oracle, target: Path | None = None, *, allow_missing: bool = False) -> int:
    """Measure the whole AGS4 set with ``oracle`` and rewrite ``target``; return the count."""
    conf = _conformance()
    target = conf.AGS4_EXPECTED if target is None else target
    external = conf.load_external(conf.AGS4_CORPUS, conf.AGS4_CACHE)
    entries = conf._require_present(
        [*external, *conf.ags4_fixtures(conf.AGS4_FIXTURES)], allow_missing=allow_missing
    )
    records = [
        measure(e.key, e.path, oracle, in_repo=e.url is None, rel=conf._rel(e.path))
        for e in entries
    ]
    target.write_text(render(oracle, records), encoding="utf-8", newline="\n")
    return len(records)


def main(argv: Sequence[str] | None = None, oracle: Oracle | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=["record"])
    parser.add_argument(
        "--allow-missing",
        action="store_true",
        help="skip external files not fetched (the record then lacks them: do not commit it)",
    )
    args = parser.parse_args(argv)
    conf = _conformance()
    try:
        if oracle is None:
            oracle = python_ags4_oracle()
        # python-ags4 logs every finding it reports; the record holds them already.
        logging.disable(logging.CRITICAL)
        try:
            count = record(oracle, allow_missing=args.allow_missing)
        finally:
            logging.disable(logging.NOTSET)
    except OracleError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except conf.CorpusError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2 if isinstance(exc, conf.ManifestError) else 1
    print(f"recorded {count} file(s) in {conf.AGS4_EXPECTED.name} ({ORACLE_NAME} {oracle.version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
