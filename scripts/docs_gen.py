#!/usr/bin/env python3
"""Generate the documentation pages that state facts about the code.

A fact written by hand goes stale the first time a pull request forgets it. Each generator
here renders a page, or a marked region of one, from the code. ``--check`` fails when the
committed copy differs, and ``tests/test_docs.py`` runs it, so CI catches a stale page.

    python scripts/docs_gen.py            rewrite the generated pages
    python scripts/docs_gen.py --check    exit 1 when a committed page is stale

To generate another page, write a function that returns Markdown and add a ``Generator`` to
``GENERATORS``. With ``region`` set, only the text between ``<!-- docs_gen:NAME:start -->``
and ``<!-- docs_gen:NAME:end -->`` is rewritten and the rest of the page stays hand-written.

The version is deliberately not on any generated page: a release bump must not make a
committed page stale. ``scripts/docs_hooks.py`` stamps it into the site at build time.

A console script's ``--help`` is run from ``src/``, so the package does not have to be
installed; the generators that read the code (``capabilities()``, the mapping table) import
it from ``src/`` and need its runtime dependencies (lxml).

pyDIGGS has three generated pages: ``docs/facts.md`` (extras, Python range, and the
``--help`` of ``pydiggs`` and of each of its commands), the operations table of
``docs/capabilities.md`` (a marked region), and ``docs/convert-mapping.md``, which
``scripts/mapping_doc.py`` also writes and checks on its own.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import subprocess
import sys
import tomllib
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
#: The oldest supported Python. ``--help`` text is captured there: argparse lays it out
#: differently from one Python version to the next.
PY_MIN = "3.11"
FLOOR = tuple(int(part) for part in PY_MIN.split("."))
SRC = ROOT / "src"

_HEADER = (
    "<!-- Generated by scripts/docs_gen.py. Do not edit: run `python scripts/docs_gen.py`. -->\n\n"
)
#: Runs in a child interpreter: ``--help`` of a console script and of each of its commands,
#: in one process, because importing the package is the slow part. Prints a JSON list of
#: ``[words, help text]``. ``commands`` optionally names a mapping (``module:attr``) whose
#: keys are the script's commands; a command whose ``--help`` has a ``COMMAND`` section lists
#: its own commands there, and those are run too.
_RUN_SCRIPT = r"""
import contextlib, importlib, io, json, re, sys

def load(ref):
    module, _, attr = ref.partition(":")
    target = importlib.import_module(module)
    for part in attr.split("[")[0].strip().split("."):
        if part:
            target = getattr(target, part)
    return target

name, entry, commands = sys.argv[1:4]
target = load(entry)

def helps(words):
    out = io.StringIO()
    sys.argv = [name, *words, "--help"]
    with contextlib.redirect_stdout(out):
        try:
            code = target()
        except SystemExit as stop:
            code = stop.code
    if code not in (0, None):
        raise SystemExit(f"`{' '.join([name, *words])} --help` exited {code}")
    return out.getvalue()

result = [[[], helps([])]]
for word in sorted(load(commands)) if commands else []:
    text = helps([word])
    result.append([[word], text])
    nested = re.search(r"^  COMMAND\n((?:    .*\n?)+)", text, re.MULTILINE)
    names = re.findall(r"^    (\w[\w-]*)(?:\s|$)", nested.group(1), re.M) if nested else []
    for sub in names:
        result.append([[word, sub], helps([word, sub])])
print(json.dumps(result))
"""
#: Console scripts whose commands are listed on the facts page, and where the code keeps them.
COMMANDS = {"pydiggs": "pydiggs.cli:_SUBCOMMANDS"}


@dataclass(frozen=True)
class Generator:
    """One generated page, or one generated region of a hand-written page."""

    path: str
    render: Callable[[], str]
    region: str = ""
    #: First line of a whole page. A renderer that writes its own leaves this empty.
    header: str = _HEADER


def project() -> dict[str, Any]:
    """Return the ``[project]`` table of pyproject.toml."""
    with (ROOT / "pyproject.toml").open("rb") as handle:
        table: dict[str, Any] = tomllib.load(handle)["project"]
    return table


def console_scripts() -> dict[str, str]:
    """Return the console scripts the package installs, name to ``module:function``."""
    scripts: dict[str, str] = project().get("scripts", {})
    return dict(sorted(scripts.items()))


def help_depends_on_interpreter() -> bool:
    """Say whether the pages hold ``--help`` text this Python would lay out differently."""
    return bool(console_scripts()) and sys.version_info[:2] != FLOOR


def script_helps(name: str, target: str) -> list[tuple[tuple[str, ...], str]]:
    """Return ``--help`` of a console script and of each command, at a fixed width.

    The output has no colour and is laid out for 80 columns. The commands are read from the
    code (``COMMANDS``), so a new command appears on the page without anyone listing it.
    """
    env = {
        **os.environ,
        "PYTHONPATH": os.pathsep.join(filter(None, [str(SRC), os.environ.get("PYTHONPATH")])),
        "COLUMNS": "80",
        "LINES": "24",
        "NO_COLOR": "1",
        "PYTHON_COLORS": "0",
    }
    env.pop("FORCE_COLOR", None)
    proc = subprocess.run(  # noqa: S603 - this interpreter, fixed argv, no shell
        [sys.executable, "-c", _RUN_SCRIPT, name, target, COMMANDS.get(name, "")],
        capture_output=True,
        text=True,
        check=False,
        env=env,
        timeout=600,
    )
    if proc.returncode != 0:
        msg = f"`{name} --help` failed ({proc.returncode}): {proc.stderr.strip()[-400:]}"
        raise RuntimeError(msg)
    return [
        (tuple(words), "\n".join(line.rstrip() for line in text.strip().splitlines()))
        for words, text in json.loads(proc.stdout)
    ]


def facts() -> str:
    """Render docs/facts.md: what pyproject.toml says the package needs and installs."""
    meta = project()
    dependencies = ", ".join(f"`{dep}`" for dep in meta.get("dependencies", [])) or "none"
    lines = [
        "# Project facts",
        "",
        "Generated from `pyproject.toml` and checked in CI, so this page cannot disagree with",
        "what is installed.",
        "",
        "| Fact | Value |",
        "|---|---|",
        f"| Distribution | `{meta['name']}` |",
        f"| Requires Python | `{meta.get('requires-python', 'not declared')}` |",
        f"| Runtime dependencies | {dependencies} |",
        "",
        "## Optional extras",
        "",
    ]
    extras: dict[str, list[str]] = meta.get("optional-dependencies", {})
    if extras:
        lines += ["| Extra | Install | Adds |", "|---|---|---|"]
        for extra, requirements in sorted(extras.items()):
            adds = ", ".join(f"`{req}`" for req in requirements) or "nothing"
            lines.append(f'| `{extra}` | `pip install "{meta["name"]}[{extra}]"` | {adds} |')
    else:
        lines.append("None.")
    lines += ["", "## Command-line scripts", ""]
    scripts = console_scripts()
    if not scripts:
        lines.append("None.")
    for name, target in scripts.items():
        # `pydiggs validate --help` and the others are their own parsers: the page is the
        # command-line reference, so each one is here.
        for words, text in script_helps(name, target):
            heading = "###" if not words else "####"
            title = " ".join([name, *words])
            lines += [f"{heading} `{title}`", "", "```text", text, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def capabilities_table() -> str:
    """Render the operations of ``pydiggs.capabilities()``: id, stability, extras, label."""
    sys.path.insert(0, str(SRC))
    try:
        import pydiggs  # noqa: PLC0415 - from src/, so the installed copy cannot answer
    finally:
        sys.path.remove(str(SRC))
    lines = [
        "| id | stability | needs | what it does |",
        "|---|---|---|---|",
    ]
    for op in pydiggs.capabilities().operations:
        needs = ", ".join(f"`{extra}`" for extra in op.needs)
        lines.append(f"| `{op.id}` | {op.stability} | {needs} | {op.label} |")
    return "\n".join(lines) + "\n"


def mapping_page() -> str:
    """Render docs/convert-mapping.md with scripts/mapping_doc.py, which also checks it."""
    script = ROOT / "scripts" / "mapping_doc.py"
    spec = importlib.util.spec_from_file_location("mapping_doc", script)
    if spec is None or spec.loader is None:
        msg = f"cannot load {script}"
        raise RuntimeError(msg)
    module = importlib.util.module_from_spec(spec)
    sys.modules["mapping_doc"] = module
    spec.loader.exec_module(module)
    page: str = module.render(module.load_mapping())
    return page


GENERATORS: tuple[Generator, ...] = (
    Generator("docs/facts.md", facts),
    Generator("docs/capabilities.md", capabilities_table, region="operations"),
    Generator("docs/convert-mapping.md", mapping_page, header=""),
)


def expected(generator: Generator) -> str:
    """Return what the generator's file should contain now.

    Raises:
        ValueError: A region generator's markers are missing from its page.
    """
    body = generator.render()
    if not generator.region:
        return generator.header + body
    start = f"<!-- docs_gen:{generator.region}:start -->"
    end = f"<!-- docs_gen:{generator.region}:end -->"
    text = (ROOT / generator.path).read_text(encoding="utf-8")
    before, found_start, rest = text.partition(start)
    _, found_end, after = rest.partition(end)
    if not (found_start and found_end):
        msg = f"{generator.path} has no `{start}` ... `{end}` markers"
        raise ValueError(msg)
    return f"{before}{start}\n{body.strip()}\n{end}{after}"


def stale() -> list[str]:
    """Return the generated files whose committed copy differs from the code."""
    found = []
    for generator in GENERATORS:
        path = ROOT / generator.path
        # read_text gives \n for either line ending, so a CRLF checkout is not "stale".
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != expected(generator):
            found.append(generator.path)
    return found


def main(argv: list[str] | None = None) -> int:
    """Rewrite the generated pages, or with ``--check`` report the stale ones."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a page is stale")
    args = parser.parse_args(argv)
    if args.check:
        outdated = stale()
        for page in outdated:
            print(f"stale: {page} (run `python scripts/docs_gen.py` and commit the result)")
        if outdated and console_scripts():
            print(f"--help text is captured on Python {PY_MIN}; regenerate with that version.")
        return 1 if outdated else 0
    for generator in GENERATORS:
        text = expected(generator)
        path = ROOT / generator.path
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"wrote {generator.path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
