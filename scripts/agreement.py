r"""Compare pyDIGGS's verdicts on the conformance corpus with the DIGGSml XSLT validator's.

The DIGGS project's own validator is a set of XSLT 3.0 stylesheets in
https://github.com/DIGGSml/validation (``diggs-validation.xsl`` and ``modules/``). This
script runs it on every file of the conformance corpus (``conformance/README.md``) and
compares its verdict with the one pyDIGGS records in ``conformance/expected.toml``. Every
file where the two differ must be explained in ``conformance/intended.toml``; the docs
page ``docs/conformance-agreement.md`` lists them all, with the reasons.

Pinned and offline:

* the validator's files are pinned by commit, size and sha256 in
  ``conformance/xslt-validator.toml`` (same format as ``corpus.toml``) and fetched into
  ``.cache/agreement/``; they are never committed (the repository states no licence);
* the XSLT processor is SaxonC-HE (``saxonche``), pinned with hashes in
  ``conformance/xslt-requirements.txt`` and installed in a throwaway environment only
  (``uv pip sync --require-hashes``): it is never a dependency of pyDIGGS;
* every URL the validator asks for is answered from a local copy through an XML catalog:
  the DIGGS schemas and dictionaries pyDIGGS bundles (``src/pydiggs/PROVENANCE.toml``),
  the validator's own files, and the files the manifest's ``[mirror]`` table names. Any
  other URL resolves to a file that does not exist, so the validator sees it as
  unreachable and **nothing is fetched from the network while it runs**. That includes
  the Geosetta units API the upstream dictionary module and Schematron rules call.

Usage (from the repository root)::

    # Download the validator's files (network: raw.githubusercontent.com only).
    python scripts/agreement.py fetch

    # SaxonC-HE in a throwaway environment, every wheel checked against its hash.
    uv venv --python 3.12 .cache/agreement/venv
    uv pip sync --require-hashes --python .cache/agreement/venv conformance/xslt-requirements.txt

    # Run the validator on the corpus and rewrite conformance/xslt-expected.toml.
    .cache/agreement/venv/bin/python scripts/agreement.py record

    # Run it again and compare with the record, then check every disagreement.
    .cache/agreement/venv/bin/python scripts/agreement.py check --run

    # Offline, from the records alone: is every disagreement explained?
    python scripts/agreement.py check

    # Print the page's generated part (the docs build inserts it, scripts/mkdocs_hooks.py).
    python scripts/agreement.py page

Exit codes: 0 success, 1 an unexplained or stale disagreement, a record that differs from
a new run, or a missing or corrupt file; 2 a bad manifest or usage error.
"""

