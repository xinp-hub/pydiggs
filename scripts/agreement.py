KIND_CHARS = 160


def _conformance() -> ModuleType:
    """Load ``scripts/conformance.py`` (manifest, fetch, digest) from beside us."""
    name = "conformance"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, _HERE / "conformance.py")
    if spec is None or spec.loader is None:  # pragma: no cover - the file is in the repo
        raise ImportError(name)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclasses resolve annotations through sys.modules
    try:
        spec.loader.exec_module(module)
    except BaseException:
        del sys.modules[name]
        raise
    return module


class AgreementError(Exception):
    """A record, a manifest or the explanations are malformed (exit 2)."""


# --- running the validator --------------------------------------------------------------


def message_kind(step: str, text: str) -> str:
    """Return the kind of a validator message: its step and its text without the values.

    Quoted values and numbers are replaced, whitespace collapsed and the text cut to
    :data:`KIND_CHARS`, so the same rule failing on different elements gives one kind.

    Examples:
        >>> message_kind("CRS Validation", 'The resource at "https://x/1" could not  be read')
        'CRS Validation: The resource at "…" could not be read'
        >>> message_kind("Schematron Validation", "Plunge must be between -45 and -10 degrees")
        'Schematron Validation: Plunge must be between # and # degrees'
        >>> message_kind("Dictionary Validation", 'Check 5: Code "x1" is not found')
        'Dictionary Validation: Check 5: Code "…" is not found'
    """
    body = _QUOTED.sub('"…"', text)
    body = _NUMBER.sub(lambda m: m.group(1) or "#", body)
    body = _SPACE.sub(" ", body).strip()
    if len(body) > KIND_CHARS:
        body = body[: KIND_CHARS - 1].rstrip() + "…"
    return f"{step}: {body}"


@dataclass
class XsltOutcome:
    """What the validator reported for one file.

    Attributes:
        counts: Messages by severity (``error``, ``warning``, ``info``).
        error_kinds: Every ERROR message, by :func:`message_kind`, with how many there are.
        stopped: Why the validator did not finish (Saxon raised an error), or ``""``.
    """

    counts: Counter[str] = field(default_factory=Counter)
    error_kinds: Counter[str] = field(default_factory=Counter)
    stopped: str = ""

    @property
    def ok(self) -> bool:
        """True when the validator ran to the end and reported no ERROR."""
        return not self.stopped and self.counts["error"] == 0

    def to_record(self) -> dict[str, Any]:
        """Return the outcome as one ``xslt-expected.toml`` entry."""
        record: dict[str, Any] = {
            "ok": self.ok,
            "errors": self.counts["error"],
            "warnings": self.counts["warning"],
            "infos": self.counts["info"],
        }
        if self.stopped:
            record["stopped"] = self.stopped
        if self.error_kinds:
            record["error_kinds"] = dict(sorted(self.error_kinds.items()))
        return record


def mirror_map(
    manifest: Mapping[str, Any], provenance: Path = PROVENANCE, cache: Path = CACHE
) -> dict[str, Path]:
    """Return every URL (or URL prefix, ending in ``/``) the catalog answers locally.

    From ``provenance``: each bundled file of the ``def`` and ``schemas`` sources at the
    address diggsml.org publishes it, over https and http. From the manifest's
    ``[mirror]`` table: ``"<url>" = "cache:<key>"`` (a file of the manifest, in the
    cache) or ``"package:<path>"`` (a file under ``src/pydiggs``).

    Raises:
        AgreementError: A ``[mirror]`` entry names something else.
    """
    conf = _conformance()
    data = conf._load_toml(provenance)
    mapping: dict[str, Path] = {}
    for rel, meta in data.get("files", {}).items():
        published = _PUBLISHED.get(str(meta.get("source")))
        upstream = str(meta.get("path") or "")
        if published is None or not upstream.startswith(published[0]):
            continue
        tail = upstream.removeprefix(published[0])
        if meta["source"] == "schemas" and not tail.startswith(_SCHEMA_RELEASES):
            continue
        for scheme in ("https://", "http://"):
            mapping[f"{scheme}{published[1]}{tail}"] = PACKAGE / rel
    for url, target in manifest.get("mirror", {}).items():
        where = f"{MANIFEST.name} [mirror] {url!r}"
        kind, _, rel = str(target).partition(":")
        if not url.startswith(("https://", "http://")) or kind not in {"cache", "package"}:
            msg = f"{where}: must map an http(s) URL to cache:<key> or package:<path>"
            raise AgreementError(msg)
        conf._safe_rel(rel.rstrip("/"), where)
        base = cache if kind == "cache" else PACKAGE
        path = base / rel
        if url.endswith("/") != rel.endswith("/"):
            msg = f"{where}: a prefix (ending in /) maps to a folder (ending in /)"
            raise AgreementError(msg)
        mapping[url] = path
    return mapping


def write_catalog(mapping: Mapping[str, Path], offline: Path, target: Path) -> Path:
    """Write an OASIS XML catalog: ``mapping`` locally, every other URL to nowhere.

    "Nowhere" is a file under ``offline`` that does not exist. An exact URL is a ``uri``
    entry; a prefix (ending in ``/``) is a ``rewriteURI`` entry. Catalog resolution
    prefers an exact entry, then the longest matching prefix, so the two catch-all
    prefixes (``https://`` and ``http://``) apply only when nothing else does.
    """
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Written by scripts/agreement.py: every URL the DIGGSml validator asks for. -->",
        '<catalog xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog">',
    ]
    for url in sorted(mapping):
        local = mapping[url].resolve().as_uri()
        if url.endswith("/"):
            local += "" if local.endswith("/") else "/"
            lines.append(
                f"  <rewriteURI uriStartString={quoteattr(url)} rewritePrefix={quoteattr(local)}/>"
            )
        else:
            lines.append(f"  <uri name={quoteattr(url)} uri={quoteattr(local)}/>")
    for scheme in ("https", "http"):
        nowhere = (offline.resolve() / scheme).as_uri() + "/"
        lines.append(
            f"  <rewriteURI uriStartString={quoteattr(scheme + '://')}"
            f" rewritePrefix={quoteattr(nowhere)}/>"
        )
    lines.append("</catalog>")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


#: One line per message of a validationReport: step, severity, text (tab separated).
_REPORT_XPATH = (
    "for $m in /validationReport/messageSet/message return "
    "string-join(($m/../step, upper-case(normalize-space($m/severity)), "
    "normalize-space($m/text)), codepoints-to-string(9))"
)


def summarize(lines: Iterable[str]) -> XsltOutcome:
    r"""Count the messages of a report, given as ``step<TAB>SEVERITY<TAB>text`` lines.

    Examples:
        >>> out = summarize(["CRS Validation\tERROR\tbad 1", "X\tWARNING\tw"])
        >>> out.ok, out.counts["error"], dict(out.error_kinds)
        (False, 1, {'CRS Validation: bad #': 1})
    """
    outcome = XsltOutcome()
    for line in lines:
        step, _, rest = line.partition("\t")
        severity, _, text = rest.partition("\t")
        level = severity.strip().lower()
        outcome.counts[level if level in {"error", "warning", "info"} else "info"] += 1
        if level == "error":
            outcome.error_kinds[message_kind(step.strip(), text)] += 1
    return outcome


class Validator:
    """The DIGGSml XSLT validator, compiled once with SaxonC-HE and an offline catalog."""

    def __init__(self, source: Path, catalog: Path, offline: Path) -> None:
        """Compile ``source/diggs-validation.xsl``; resolve every URL through ``catalog``.

        ``offline`` is where the catalog sends unknown URLs: it is replaced by
        ``<offline>`` in messages, so a record does not depend on the checkout's path.

        Raises:
            AgreementError: saxonche is not installed (see ``conformance/README.md``).
        """
        try:
            saxonche: Any = importlib.import_module("saxonche")
        except ImportError as exc:
            msg = (
                "saxonche is not installed; install it in a throwaway environment with "
                "uv pip sync --require-hashes "
                f"{REQUIREMENTS.relative_to(ROOT).as_posix()} (see this script's docstring)"
            )
            raise AgreementError(msg) from exc
        self._error: type[BaseException] = saxonche.PySaxonApiError
        here = offline.resolve()
        self._scrub = (
            (here.as_uri(), "<offline>"),
            (str(here), "<offline>"),
            (str(ROOT), "<root>"),
        )
        self._proc = saxonche.PySaxonProcessor(license=False)
        self.version = str(self._proc.version)
        self._proc.set_catalog_files([str(catalog)])
        xslt = self._proc.new_xslt30_processor()
        xslt.set_cwd(str(source))
        self._exe = xslt.compile_stylesheet(stylesheet_file=str(source / STYLESHEET))

    def run(self, path: Path) -> XsltOutcome:
        """Validate the file at ``path`` and return what the validator reported."""
        try:
            report = self._exe.transform_to_string(source_file=str(path))
            doc = self._proc.parse_xml(xml_text=report)
            xpath = self._proc.new_xpath_processor()
            xpath.set_context(xdm_item=doc)
            value = xpath.evaluate(_REPORT_XPATH)
        except self._error as exc:
            first = str(exc).strip().splitlines()[0] if str(exc).strip() else type(exc).__name__
            stopped = self._scrubbed(first.replace(str(path), "<file>"))
            return XsltOutcome(stopped=stopped[:KIND_CHARS])
        lines = [] if value is None else [self._scrubbed(str(item.string_value)) for item in value]
        return summarize(lines)

    def _scrubbed(self, text: str) -> str:
        for local, placeholder in self._scrub:
            text = text.replace(local, placeholder)
        return text


def corpus_entries() -> list[Any]:
    """Return the corpus files as ``conformance.Entry`` (no ``@profile`` rows).

    The validator has no way to be told a profile: it reads the schema the file names.
    """
    conf = _conformance()
    return [*conf.load_vendored(conf.VENDORED_PROVENANCE), *conf.load_external(conf.CORPUS)]


def validator_entries(manifest: Path = MANIFEST, cache: Path = CACHE) -> list[Any]:
    """Return the validator's pinned files as ``conformance.Entry``."""
    return list(_conformance().load_external(manifest, cache))


def run_all(
    entries: Sequence[Any], manifest: Path = MANIFEST, cache: Path = CACHE
) -> tuple[str, dict[str, XsltOutcome]]:
    """Run the validator on every corpus entry; return Saxon's version and the outcomes."""
    conf = _conformance()
    conf._require_present(validator_entries(manifest, cache), allow_missing=False)
    ready = conf._require_present(entries, allow_missing=False)
    data = conf._load_toml(manifest)
    catalog = write_catalog(mirror_map(data, cache=cache), cache / "offline", cache / "catalog.xml")
    validator = Validator(cache / "validation", catalog, cache / "offline")
    outcomes = {}
    for entry in ready:
        print(f"validating {entry.key}", file=sys.stderr)
        outcomes[entry.key] = validator.run(entry.path)
    return validator.version, outcomes


def render_records(outcomes: Mapping[str, XsltOutcome]) -> str:
    """Return the text of ``xslt-expected.toml`` for ``outcomes`` (sorted, stable)."""
    conf = _conformance()
    return str(conf.render_expected({k: o.to_record() for k, o in outcomes.items()}, _HEADER))


# --- explaining the disagreements -------------------------------------------------------


@dataclass(frozen=True)
class Reason:
    """One documented cause of a disagreement (``[reasons.<id>]`` in intended.toml).

    Attributes:
        id: The reason's id, used by the files that cite it and as the page anchor.
        title: One line, shown in the table.
        side: ``xslt`` when the validator reports an error pyDIGGS does not, ``pydiggs``
            when pyDIGGS does and the validator does not.
        kinds: For ``xslt``: regular expressions; an error kind is explained when one of
            them matches it (``re.search``).
        rules: For ``pydiggs``: shell patterns (``fnmatch``) of the pyDIGGS rule ids it
            explains.
        why: The explanation, in Markdown, for the page.
        upstream: An issue or a link where the difference is tracked, if any.
    """

    id: str
    title: str
    side: str
    kinds: tuple[str, ...] = ()
    rules: tuple[str, ...] = ()
    why: str = ""
    upstream: str = ""

    def explains_kind(self, kind: str) -> bool:
        """True when this ``xslt`` reason covers the error kind ``kind``."""
        return self.side == "xslt" and any(re.search(p, kind) for p in self.kinds)

    def explains_rule(self, rule: str) -> bool:
        """True when this ``pydiggs`` reason covers the pyDIGGS rule id ``rule``."""
        return self.side == "pydiggs" and any(fnmatch.fnmatchcase(rule, p) for p in self.rules)


_REASON_ID = re.compile(r"[a-z0-9][a-z0-9-]{0,63}")


def load_intended(path: Path = INTENDED) -> tuple[dict[str, Reason], dict[str, list[str]]]:
    """Return the reasons and, for every file listed, the ids of the reasons it cites.

    Raises:
        AgreementError: The file is malformed.
    """
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        msg = f"{path.name}: {exc}"
        raise AgreementError(msg) from exc
    reasons: dict[str, Reason] = {}
    for rid, meta in data.get("reasons", {}).items():
        where = f"{path.name} [reasons.{rid}]"
        if not _REASON_ID.fullmatch(rid) or not isinstance(meta, dict):
            msg = f"{where}: an id is lowercase letters, digits and hyphens"
            raise AgreementError(msg)
        side = meta.get("side")
        kinds = tuple(str(k) for k in meta.get("kinds", ()))
        rules = tuple(str(r) for r in meta.get("rules", ()))
        if side not in {"xslt", "pydiggs"} or not meta.get("title") or not meta.get("why"):
            msg = f"{where}: needs side (xslt or pydiggs), title and why"
            raise AgreementError(msg)
        if (side == "xslt") != bool(kinds) or (side == "pydiggs") != bool(rules):
            msg = f"{where}: an xslt reason lists kinds, a pydiggs reason lists rules"
            raise AgreementError(msg)
        for pattern in kinds:
            try:
                re.compile(pattern)
            except re.error as exc:
                msg = f"{where}: kinds {pattern!r}: {exc}"
                raise AgreementError(msg) from exc
        reasons[rid] = Reason(
            rid,
            str(meta["title"]),
            side,
            kinds,
            rules,
            str(meta["why"]).strip(),
            str(meta.get("upstream", "")),
        )
    files: dict[str, list[str]] = {}
    for key, meta in data.get("files", {}).items():
        cited = meta.get("reasons") if isinstance(meta, dict) else None
        if not isinstance(cited, list) or not cited or not all(isinstance(r, str) for r in cited):
            msg = f"{path.name} [files.{key!r}]: reasons must be a non-empty list of ids"
            raise AgreementError(msg)
        files[key] = list(cited)
    return reasons, files


@dataclass(frozen=True)
class Row:
    """One corpus file on the page: both verdicts and, where they differ, why."""

    key: str
    pydiggs: Mapping[str, Any]
    xslt: Mapping[str, Any]
    reasons: tuple[str, ...] = ()

    @property
    def agree(self) -> bool:
        """True when both give the same verdict (valid, or not)."""
        return bool(self.pydiggs.get("ok")) == bool(self.xslt.get("ok"))


def _load(path: Path) -> dict[str, Any]:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        msg = f"{path.name}: {exc}"
        raise AgreementError(msg) from exc


def rows(
    expected: Mapping[str, Any], xslt: Mapping[str, Any], cited: Mapping[str, list[str]]
) -> list[Row]:
    """Pair every corpus file's two outcomes; ``@profile`` rows of pyDIGGS are left out."""
    keys = sorted(k for k in expected if "@" not in k)
    return [
        Row(k, expected[k], xslt.get(k, {}), tuple(cited.get(k, ()))) for k in keys if k in xslt
    ]


def _unexplained(row: Row, reasons: Mapping[str, Reason]) -> list[str]:
    """Return what in ``row`` the reasons it cites do not explain (empty when all is)."""
    cited = [reasons[r] for r in row.reasons if r in reasons]
    if bool(row.pydiggs.get("ok")):
        # The validator fails a file pyDIGGS passes: every error kind must be covered.
        kinds = list(row.xslt.get("error_kinds", {}))
        if row.xslt.get("stopped"):
            kinds.append(f"{STOPPED}: {row.xslt['stopped']}")
        return [f"XSLT {k}" for k in kinds if not any(r.explains_kind(k) for r in cited)]
    rules = list(row.pydiggs.get("error_rules", []))
    return [f"pyDIGGS {r}" for r in rules if not any(r_.explains_rule(r) for r_ in cited)]


def explain(
    expected: Mapping[str, Any],
    xslt: Mapping[str, Any],
    reasons: Mapping[str, Reason],
    cited: Mapping[str, list[str]],
) -> list[str]:
    """Return one line per problem with the explanations; empty when all is explained.

    A problem is: a corpus file with no record on one side; a disagreement with no entry
    in intended.toml, or with something its reasons do not cover; an entry for a file
    that agrees (stale) or is not in the corpus; a reason cited but not defined, cited
    where it does not apply, or never cited.
    """
    problems: list[str] = []
    base = {k for k in expected if "@" not in k}
    problems += [
        f"{k}: no record of the XSLT validator (run record)" for k in sorted(base - set(xslt))
    ]
    problems += [
        f"{k}: in xslt-expected.toml but not in the corpus" for k in sorted(set(xslt) - base)
    ]
    problems += [f"{k}: in intended.toml but not in the corpus" for k in sorted(set(cited) - base)]
    used: set[str] = set()
    for row in rows(expected, xslt, cited):
        unknown = [r for r in row.reasons if r not in reasons]
        problems += [f"{row.key}: reason {r!r} is not defined in intended.toml" for r in unknown]
        if row.agree:
            if row.key in cited:
                problems.append(f"{row.key}: the verdicts agree now; remove it from intended.toml")
            continue
        if row.key not in cited:
            problems.append(f"{row.key}: verdicts differ and intended.toml does not say why")
            continue
        used.update(row.reasons)
        problems += [f"{row.key}: not explained: {what}" for what in _unexplained(row, reasons)]
        for rid in row.reasons:
            reason = reasons.get(rid)
            if reason is not None and not _applies(reason, row):
                problems.append(f"{row.key}: reason {rid!r} does not apply to this file")
    problems += [f"reason {r!r} is not cited by any file" for r in sorted(set(reasons) - used)]
    return problems


def _applies(reason: Reason, row: Row) -> bool:
    if reason.side == "xslt":
        kinds = list(row.xslt.get("error_kinds", {}))
        if row.xslt.get("stopped"):
            kinds.append(f"{STOPPED}: {row.xslt['stopped']}")
        return row.pydiggs.get("ok") is not False and any(reason.explains_kind(k) for k in kinds)
    return row.xslt.get("ok") is not False and any(
        reason.explains_rule(r) for r in row.pydiggs.get("error_rules", [])
    )


def compare_records(recorded: Mapping[str, Any], fresh: Mapping[str, XsltOutcome]) -> list[str]:
    """Return one line per field where a new run differs from ``xslt-expected.toml``."""
    problems = [f"{k}: recorded but not run" for k in sorted(set(recorded) - set(fresh))]
    for key in sorted(fresh):
        got = fresh[key].to_record()
        want = recorded.get(key)
        if want is None:
            problems.append(f"{key}: no record (run record and review)")
            continue
        problems.extend(
            f"{key}: {name} recorded {want.get(name)!r}, got {got.get(name)!r}"
            for name in sorted(set(got) | set(want))
            if got.get(name) != want.get(name)
        )
    return problems


# --- the docs page ----------------------------------------------------------------------


def _cell(text: str) -> str:
    """Escape ``text`` for a Markdown table cell (file names come from upstream)."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("<", "&lt;").replace("`", "'")


def _verdict(outcome: Mapping[str, Any], *, xslt: bool) -> str:
    if xslt and outcome.get("stopped"):
        return "stopped"
    word = "valid" if outcome.get("ok") else "**invalid**"
    counts = f"{outcome.get('errors', 0)} E, {outcome.get('warnings', 0)} W"
    if xslt:
        counts += f", {outcome.get('infos', 0)} I"
    return f"{word} ({counts})"


def render_page(
    expected: Mapping[str, Any],
    xslt: Mapping[str, Any],
    reasons: Mapping[str, Reason],
    cited: Mapping[str, list[str]],
    manifest: Mapping[str, Any],
) -> str:
    """Return the generated part of ``docs/conformance-agreement.md`` (Markdown)."""
    table = rows(expected, xslt, cited)
    differ = [r for r in table if not r.agree]
    problems = explain(expected, xslt, reasons, cited)
    sources = manifest.get("sources", {})
    validation = sources.get("validation", {})
    commit = str(validation.get("commit", ""))
    processor = manifest.get("validator", {}).get("processor", "")
    lines = [
        f"**{len(table)} files, {len(table) - len(differ)} with the same verdict, "
        f"{len(differ)} with different verdicts"
        + (", every one explained below.**" if not problems else ".**"),
        "",
        "| | |",
        "| --- | --- |",
        f"| Validator | [DIGGSml/validation]({validation.get('repo', '')}) at "
        f"[`{commit[:7]}`]({validation.get('repo', '')}/tree/{commit}) |",
        f"| XSLT processor | {_cell(str(processor))} |",
        "| pyDIGGS | the outcomes recorded in `conformance/expected.toml` |",
        "",
    ]
    if problems:
        lines += [
            '!!! failure "Not explained"',
            "    The agreement check fails on this build:",
            "",
            *(f"    - {_cell(p)}" for p in problems),
            "",
        ]
    lines += ["## Where the verdicts differ", ""]
    if differ:
        lines += ["| File | pyDIGGS | XSLT validator | Why |", "| --- | --- | --- | --- |"]
        for row in differ:
            why = ", ".join(
                f"[{_cell(reasons[r].title)}](#{r})" if r in reasons else _cell(r)
                for r in row.reasons
            )
            lines.append(
                f"| `{_cell(row.key)}` | {_verdict(row.pydiggs, xslt=False)} "
                f"| {_verdict(row.xslt, xslt=True)} | {why or '**not explained**'} |"
            )
    else:
        lines.append("None.")
    lines += ["", "## Reasons", ""]
    for rid, reason in reasons.items():
        files = [r.key for r in differ if rid in r.reasons]
        lines += [f"### {reason.title} {{#{rid}}}", "", reason.why, ""]
        if reason.upstream:
            lines += [f"Tracked: {reason.upstream}", ""]
        side = (
            "The XSLT validator reports an error that pyDIGGS does not."
            if reason.side == "xslt"
            else "pyDIGGS reports an error that the XSLT validator does not."
        )
        lines += [f"{side} Files: {len(files)}.", ""]
    lines += [
        "## Every file",
        "",
        "E, W, I: errors, warnings and information messages. The XSLT validator's error "
        "messages are listed by kind (its own text, with values left out).",
        "",
        "| File | pyDIGGS | XSLT validator | Same verdict |",
        "| --- | --- | --- | --- |",
    ]
    for row in table:
        lines.append(
            f"| `{_cell(row.key)}` | {_verdict(row.pydiggs, xslt=False)} "
            f"| {_verdict(row.xslt, xslt=True)} | {'yes' if row.agree else '**no**'} |"
        )
    kinds: Counter[str] = Counter()
    for row in table:
        kinds.update(row.xslt.get("error_kinds", {}))
    if kinds:
        lines += [
            "",
            "## The XSLT validator's errors, by kind",
            "",
            "| Kind | Messages | Files |",
            "| --- | --- | --- |",
        ]
        for kind, count in sorted(kinds.items(), key=lambda kv: (-kv[1], kv[0])):
            n_files = sum(1 for r in table if kind in r.xslt.get("error_kinds", {}))
            lines.append(f"| {_cell(kind)} | {count} | {n_files} |")
    return "\n".join(lines) + "\n"


def page_from_records(
    expected_path: Path = EXPECTED,
    xslt_path: Path = XSLT_EXPECTED,
    intended_path: Path = INTENDED,
    manifest_path: Path = MANIFEST,
) -> str:
    """Return the page's generated part from the committed records."""
    reasons, cited = load_intended(intended_path)
    return render_page(_load(expected_path), _load(xslt_path), reasons, cited, _load(manifest_path))


# --- command line -----------------------------------------------------------------------


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=["fetch", "record", "check", "page"])
    parser.add_argument(
        "--run",
        action="store_true",
        help="check: run the validator and compare with xslt-expected.toml first",
    )
    args = parser.parse_args(argv)
    conf = _conformance()
    try:
        if args.command == "fetch":
            entries = validator_entries()
            for key in conf.fetch(entries):
                print(f"fetched {key}")
            print(f"{len(entries)} validator file(s) present")
            return 0
        if args.command == "page":
            sys.stdout.write(page_from_records())
            return 0
        problems: list[str] = []
        if args.command == "record" or args.run:
            version, fresh = run_all(corpus_entries())
            print(f"{version}: {len(fresh)} file(s) validated", file=sys.stderr)
            if args.command == "record":
                XSLT_EXPECTED.write_text(render_records(fresh), encoding="utf-8")
                print(f"recorded {len(fresh)} file(s) in {XSLT_EXPECTED.name}")
                return 0
            problems += compare_records(_load(XSLT_EXPECTED), fresh)
        reasons, cited = load_intended()
        problems += explain(_load(EXPECTED), _load(XSLT_EXPECTED), reasons, cited)
    except AgreementError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except conf.CorpusError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2 if isinstance(exc, conf.ManifestError) else 1
    for line in problems:
        print(line)
    print(f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
